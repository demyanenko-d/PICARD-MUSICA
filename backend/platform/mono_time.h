#pragma once

// Монотонные микросекунды для логики: таймауты, сроки, отметки в кольцах
// трассировки. Отличается от clock.h, где счётчик нужен только для замеров
// занятости и на ПК всегда ноль.
//
// На плате - встроенное чтение регистра таймера: зовут обработчики шины, на
// каждую команду хоста, и внешний вызов там лишний. Вне платы функция
// только объявлена, определяет её сборка: тестам нужны свои часы, которые
// двигает сам тест - правила по времени (отъём шины у ушедшего владельца,
// окно переинициализации карты) иначе не проверить.
//
// Счётчик 32-битный и заворачивается раз в 71.6 минуты: сравнивать только
// разности, беззнаковая арифметика заворот переживает.

#include <cstdint>

#if PICO_ON_DEVICE
#include "pico.h" // pico/platform.h напрямую не включается (#error)
#include "hardware/timer.h"
#endif

namespace platform {

#if PICO_ON_DEVICE
inline uint32_t mono_us() {
    return time_us_32();
}
// Пауза занятым ожиданием. Не сон планировщика: на плате её зовёт Core1 с
// шиной, а сон идёт через пул будильников SDK с запретом прерываний.
inline void busy_wait(uint32_t us) {
    busy_wait_us(us);
}
#else
uint32_t mono_us();
void busy_wait(uint32_t us);
#endif

} // namespace platform
