// Ключи сборки прошивки RP2350: раскладка флеша, шина и устройства,
// диагностика. Ядро их не читает. Значения под #ifndef переопределяются
// через -D.

// --- Флеш и банк ---

// Банк инструментов для .mid лежит во флеше отдельной областью, а не внутри
// образа прошивки: банк меняется редко, а запись прошивки по SWD вместе с
// ним занимала бы минуту. Прошивке хватает мегабайта с запасом, банку
// остаётся 15 МБ из 16. Читается прямо через XIP.
#define SOUNDSINTH_BANK_FLASH_OFFSET (1u * 1024u * 1024u)

// Имя в корне карты. Формат 8.3, чтобы файл был виден и без поддержки
// длинных имён.
#ifndef SOUNDSINTH_BANK_SD_PATH
#define SOUNDSINTH_BANK_SD_PATH "/midi.ssb"
#endif

// --- Шина и устройства ---

// Порты шины Z80: состояние и команды, данные. Совпадают с
// BUS_PORT_CMD/BUS_PORT_DAT клиента шины на стороне Z80 - разойдутся,
// обмен встанет молча. A0=1, A1=1, A5=1: мимо ULA, 7FFD/1FFD/DFFD/FFFD, AY
// и Kempston; различаются A2. Конфликт один - VV55 у ZX Profi.
#ifndef SOUNDSINTH_BUS_PORT_CMD
#define SOUNDSINTH_BUS_PORT_CMD 0x63
#endif
#ifndef SOUNDSINTH_BUS_PORT_DAT
#define SOUNDSINTH_BUS_PORT_DAT 0x67
#endif

// Ловушка на 0x3D00-0x3DFF - вход BDI. На настоящем железе окно
// перехватывает ПЗУ TR-DOS; у нас безусловно: любая выборка в окне
// подставляет наш банк вместо памяти машины. Ловится всё окно, а не две
// точки входа: betadisk.sys ставит обработчики где угодно в окне. Цена: в
// машине без Beta Disk процессор после NMI идёт по 3D00, 3D01 и дальше как
// по NOP. 0 - окно не ловится, остаются прочие точки входа DivMMC.
#ifndef SOUNDSINTH_DIVMMC_TRDOS_TRAP
#define SOUNDSINTH_DIVMMC_TRDOS_TRAP 1
#endif

// Сколько секторов по 512 байт держит кэш арбитра носителя. Кэш не для
// скрытия задержки - сектор с карты на 25 МГц читается за ~200 мкс, а Z80
// забирает те же 512 байт миллисекундами. Он для повторов: таблица FAT и
// каталог читаются снова и снова. 8 секторов - 4 КБ SRAM.
#define SOUNDSINTH_RP2350_STORAGE_CACHE_SECTORS 8u

// --- Диагностика ---

// След переключений DivMMC: кольцо в памяти, не обнуляемой при старте, и
// его печать при следующей загрузке. По нему видно, что делал esxDOS перед
// тем, как машина встала, - по счётчикам это неразличимо.
//
// Выключен по умолчанию. Включённый стоит 1032 байта SRAM и 440 мс каждой
// загрузки: 128 строк на 115200, а до планировщика печать блокирующая.
// Включать на время разбора падения.
#ifndef SOUNDSINTH_DIVMMC_TRACE
#define SOUNDSINTH_DIVMMC_TRACE 0
#endif
