#pragma once

// Эмулятор SD-карты в режиме SPI - то, что хост принимает за карту.
//
// Хост тактирует карту байт за байтом через порты, модуль разбирает
// команды, отдаёт токены и данные, принимает записываемый блок. Данные
// берутся через арбитр носителя, поэтому одной физической картой
// пользуются и хост, и код на МК.
//
// Контексты:
//   sd_spi_select/sd_spi_byte - из ISR обработчиков портов: только
//                         состояние и буфер, без обращений к носителю (они
//                         блокирующие);
//   sd_spi_task         - из цикла Core1: только здесь чтение и запись
//                         сектора.
//
// Пока сектор едет, хост получает 0xFF - по спецификации "данные ещё не
// готовы", драйверы такое ожидание переживают.

#include <cstdint>

namespace devices::sd {
// Эмуляторов два: DivMMC (порты 0xE7/0xEB) и Z-Controller (0x77/0x57).
// Автомат у каждого свой, общий только носитель; невыбранная сторона
// отдаёт 0xFF.
//
// Хозяева идут первыми, None последним: значение хозяина - это индекс
// автомата и носителя, и заводить пустой нулевой элемент значило бы
// держать целый автомат карты с двумя буферами сектора ни для чего.
// None остаётся признаком "писателя нет" и в индекс не годится.
enum class SdOwner : uint8_t { DivMmc = 0, ZController = 1, None = 2 };

// Три строки в лог: кто выбран и единственный писатель, отклонённые
// записи, застревания; по сторонам команды с приростом за период, чтения
// сектора и последняя команда; ожидание заказа и брошенные хостом чтения.
// Звать из задачи логгера по расписанию.
void sd_spi_log_stats();

// След последних команд карты в лог - один раз на каждый новый ошибочный
// ответ (иначе первая ошибка утопит лог). Звать из задачи логгера на
// каждом проходе.
void sd_spi_log_trace_if_new();

// Состояние "карта только что вставлена".
void sd_spi_emu_init();

// Выбор: select = true - CS опущен, карта слушает.
void sd_spi_select(SdOwner who, bool select);

// Один такт обмена: хост отдал mosi, карта отвечает возвращаемым.
uint8_t sd_spi_byte(SdOwner who, uint8_t mosi);

// Сверить свойства носителя с действительностью: флешка встаёт позже
// подъёма эмулятора, карту вынимают на ходу, а эмулятор с отсутствующим
// носителем молча отбрасывает байты хоста. Зовёт sd_spi_task.
void sd_spi_emu_refresh_media();

// Отложенные обращения к носителю. Звать из цикла Core1 как можно чаще.
void sd_spi_task();

// Сколько раз носитель не отдал заказанный сектор этой стороне. Растёт в
// цикле Core1; хост видит это таймаутом и ничем больше.
uint32_t sd_spi_media_failures(SdOwner who);

} // namespace devices::sd
