// Table of band-limited steps for edge chips (AY/YM and kin):
// backend/core/chips/blep_table.inc.
//
// Row p is the step that happens at fraction p / PHASES of a sample, as
// deltas over TAPS output samples (delay TAPS / 2). The row is the
// difference of the integrated windowed sinc (Blackman, cutoff CUTOFF of
// the sample rate) and is scaled to Q15 so that every row sums to exactly
// 32768: the integrator then returns to the same level after any sequence
// of steps.
//
// Usage: node scripts/tools/gen_blep.js > backend/core/chips/blep_table.inc

const TAPS = 16;
const PHASES = 32;
const CUTOFF = 0.45; // of the sample rate: 0.9 of Nyquist
const HALF = TAPS / 2;
const SUB = 256; // integration steps per sample

function impulse(t) {
    if (t <= -HALF || t >= HALF) return 0;
    const x = 2 * CUTOFF * t;
    const sinc = x === 0 ? 1 : Math.sin(Math.PI * x) / (Math.PI * x);
    const w = 0.42 + 0.5 * Math.cos((Math.PI * t) / HALF) + 0.08 * Math.cos((2 * Math.PI * t) / HALF);
    return 2 * CUTOFF * sinc * w;
}

// Integral of the impulse over [a, b], midpoint rule.
function integral(a, b) {
    const n = Math.max(1, Math.round((b - a) * SUB));
    const h = (b - a) / n;
    let s = 0;
    for (let i = 0; i < n; i++) s += impulse(a + (i + 0.5) * h);
    return s * h;
}

const rows = [];
for (let p = 0; p < PHASES; p++) {
    const frac = p / PHASES;
    const row = [];
    let total = 0;
    for (let k = 0; k < TAPS; k++) {
        const v = integral(k - HALF - frac, k + 1 - HALF - frac);
        row.push(v);
        total += v;
    }
    const q = row.map((v) => Math.round((v / total) * 32768));
    let sum = q.reduce((a, b) => a + b, 0);
    // Exact sum: the largest tap takes the rounding.
    let big = 0;
    for (let k = 1; k < TAPS; k++) if (q[k] > q[big]) big = k;
    q[big] += 32768 - sum;
    rows.push(q);
}

let out = "// SPDX-License-Identifier: MIT\n";
out += "// Generated by scripts/tools/gen_blep.js, do not edit.\n";
out += `// taps ${TAPS}, phases ${PHASES}, cutoff ${CUTOFF} of the sample rate, Blackman.\n`;
for (const r of rows) out += "    {" + r.map((v) => String(v)).join(", ") + "},\n";
process.stdout.write(out);
