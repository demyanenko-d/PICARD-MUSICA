#pragma once

// Сеть для поставщика виртуального диска: HTTP GET к zxart.ee. Определяет
// порт.
//
// Запрос один за раз. Ответ порт отдаёт вызовами net::zxart::zxart_http_*
// изнутри net_pump - в потоке того, кто её зовёт, то есть там же, где
// работают диск и поставщик.

#include <cstdint>

namespace net::hal {

// Сеть поднята и запрос можно начать.
bool net_ready();

// Начать GET пути. false - сеть не готова, прошлый запрос ещё идёт или
// путь длиннее буфера транспорта. Строка пути копируется: после вызова
// её можно переписывать. stream - тело принимается не быстрее, чем его
// берёт поставщик (zxart_http_room): транспорт придерживает сеть.
bool net_http_get(const char* path, bool stream);

// Бросить начатый запрос: его остаток не доставляется.
void net_http_cancel();

// Отдать поставщику то, что пришло с прошлого вызова. Звать с цикла.
void net_pump();

} // namespace net::hal
