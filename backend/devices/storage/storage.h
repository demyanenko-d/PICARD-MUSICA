#pragma once

// Арбитр носителя: через него к карте обращаются все. Прямых обращений
// к sd_card_spi.h мимо него быть не должно.
//
// Этот заголовок - только чтение. Клиентов двое: эмулятор карты (хост,
// читает и пишет) и код на МК (только читает). Хост идёт первым: фоновое
// чтение перед каждым обращением к носителю пропускает его заказы, и
// очередь решает арбитр, а не клиент. Запись - в отдельном
// storage_host.h, его включает только эмулятор.
//
// Не из ISR: обращение к носителю блокирующее, а обработчики портов
// обязаны возвращаться сразу. При старте зовёт Core0 до запуска Core1
// (storage_init, bank_sd_open), дальше только цикл Core1. В каждый момент
// поток один, поэтому внутри нет блокировок и атомиков.

#include <cstdint>

#include "devices/hal/media.h"

namespace devices::storage {

inline constexpr uint32_t kSectorBytes = devices::hal::kSectorBytes;

// Строк кэша чтения. Кэш не для скрытия задержки - сектор читается за
// сотни микросекунд, а хост забирает те же 512 байт миллисекундами. Он для
// повторов: таблица FAT и каталог читаются снова и снова. Каждая строка -
// сектор SRAM.
#ifndef SOUNDSINTH_STORAGE_CACHE_SECTORS
#define SOUNDSINTH_STORAGE_CACHE_SECTORS 8u
#endif
inline constexpr uint32_t kCacheSectors = SOUNDSINTH_STORAGE_CACHE_SECTORS;

// Поднять носитель (карта на SPI1). Зовётся один раз при старте;
// повторный вызов сбросит кэш и переинициализирует карту.
bool storage_init();

// Кто спрашивает. Носителей два, и достаются они разным клиентам:
//
//   Host  - эмуляторы карты для Z80 (DivMMC, Z-Controller). Им отдаётся
//           флешка, если она воткнута, иначе карта;
//   Board - код платы: банк .mid и файловая система. Ему всегда карта.
//
// Разделение задано назначением, а не старшинством: банк живёт на карте, а
// флешка нужна машине как её "SD-карта".
enum class Client : uint8_t { Host, Board };

bool storage_present(Client who);
uint32_t storage_sector_count(Client who);

// Прочитать сектор, из кэша или с носителя. false - носителя нет или он
// не ответил.
bool storage_read(uint32_t lba, uint8_t* dst);

// То же для фоновых клиентов (банк .mid): перед обращением к носителю
// ждущие заказы хоста уходят первыми, хост ждёт не дольше одного сектора.
bool storage_read_background(uint32_t lba, uint8_t* dst);

// Чем пропустить хост вперёд: функция, забирающая его заказы. Ставит цикл
// Core1; пока не поставлена (старт на Core0), фоновое чтение - как обычное.
void storage_set_host_yield(void (*fn)(void*), void* user);

// Строка здоровья носителя в лог (сбои чтения по причинам). Звать из
// задачи логгера по расписанию.
void storage_log_health();

// Самопроверка при старте: поднять носитель, напечатать рукопожатие,
// прочитать сектор 0 и разобрать его. Сигнатура 0x55AA означает, что
// прошли команды, данные и разбор ёмкости. Таблица разделов печатается
// целиком: хост читает тот же сектор, и пустая таблица для него то же, что
// отсутствие карты - по обмену это от нашей ошибки не отличить.
//
// sector - буфер на kSectorBytes от вызывающего: глубина чтения не
// замерена, а стек до планировщика короткий. Возвращает, поднялся ли
// носитель. Строка без перевода в конце: время старта дописывает
// вызывающий.
bool storage_boot_check(uint8_t* sector);

} // namespace devices::storage
