#pragma once

// Носитель под арбитром: всё платформенное, что ему нужно. Определяет порт.
//
// Единица - сектор в 512 байт. Не из ISR: обмен блокирующий, сектор на
// карте по SPI - около 200 мкс. Пересечений границы одно на сектор, поэтому
// это объявления, а не шаблон: вызов теряется на фоне самого обмена.

#include <cstdint>

namespace devices::hal {

inline constexpr uint32_t kSectorBytes = 512;

// Носителей два, и они не взаимозаменяемы: карта на своей шине есть
// всегда, флешка появляется и исчезает вместе с разъёмом.
enum class Medium : uint8_t { Card, Usb };

// Поднять карту. Повторный вызов - переинициализация. Флешку поднимать
// нечем: она появляется сама, когда её воткнут.
bool media_init();

// Спрашивают драйвер напрямую. Путь у обоих лежит через флеш: у карты
// через протокол SPI, у флешки через стек USB. Для горячего пути есть
// снимок ниже.
bool media_present(Medium m);
uint32_t media_sector_count(Medium m);

// --- Снимок состояния носителей ---
//
// Те же два числа, но в SRAM: цикл шины спрашивает их тысячи раз в
// секунду, а меняются они считанные разы за работу. Снимок читают
// горячие пути (поиск в кэше секторов, сверка эмулятора карты), драйверы
// они при этом не трогают вовсе.
//
// Двигают снимок только события: подъём и переинициализация карты,
// появление и исчезновение флешки. Поколение растёт на каждое изменение -
// по нему сверка эмулятора отличает "ничего не менялось" одним словом.
struct MediaState {
    bool present     = false;
    uint32_t sectors = 0;
};

const MediaState& media_state(Medium m);

// Растёт при каждом изменении снимка. Читать до полей: публикация идёт
// полями вперёд, поколением последним.
uint32_t media_state_generation();

// Перечитать носитель у драйвера и опубликовать. Звать из событий, не с
// горячего пути: внутри те же обращения во флеш, что у media_present.
void media_state_publish(Medium m);

bool media_read(Medium m, uint32_t lba, uint8_t* dst);
bool media_write(Medium m, uint32_t lba, const uint8_t* src);

// Пачка подряд идущих секторов одной командой. Смысл в накладных
// расходах: у флешки замер дал 469 мкс на команду при 426 мкс на сам
// сектор, то есть пачка из восьми вдвое дешевле восьми одиночных.
//
// Носитель, у которого пачка не дешевле, реализует это циклом - ответ
// тот же, выгоды нет. Сколько брать, говорит media_run_sectors.
bool media_read_run(Medium m, uint32_t lba, uint32_t count, uint8_t* dst);

// Сколько секторов брать одной командой, чтобы это окупалось. Единица -
// пачкой не дешевле, читать по одному. Число из замера, не из расчёта:
// дальше восьми у флешки выигрыш уже почти не растёт.
uint32_t media_run_sectors(Medium m);

// Строка здоровья носителя в журнал. Звать по расписанию, не из ISR.
void media_log_health();

} // namespace devices::hal
