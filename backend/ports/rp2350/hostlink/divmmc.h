#pragma once

// DivMMC: подстановка своего ПЗУ и ОЗУ в окно 0x0000-0x3FFF.
//
// Раскладка окна:
//
//   0x0000-0x1FFF   ПЗУ DivMMC, 8 КБ, не переключается
//   0x2000-0x3FFF   ОЗУ DivMMC, одна из шестнадцати страниц по 8 КБ
//
// Подстановка включена, если включена любым из двух путей:
//
//   порт 0xE3, бит 7 (CONMEM) - прямое указание программы;
//   трапы по адресам выборки команды - автоматический вход и выход.
//
// MAPRAM - бит 6 порта: вместо ПЗУ DivMMC страница ОЗУ 3.

#include <stdint.h>

#include "firmware_config.h" // SOUNDSINTH_DIVMMC_TRDOS_TRAP
#include "pico.h"

namespace bus {

// Окно BDI 0x3D00-0x3DFF: выборка команды оттуда - вход в TR-DOS.
inline constexpr uint32_t kBdiWindow = 0x3D00;

// Состояние после сброса: подстановка выключена, страница 0.
void divmmc_reset();

// Разбор слова, снятого автоматом записи (bus_wr).
//
// В слове весь порт ввода: бит 7 - MREQ_N, бит 6 - IORQ_N, биты 8..23 -
// адрес, биты 24..31 - данные. По ним видно, запись в память или в порт.
//
// Вызывается из прерывания. Запись в ОЗУ - одна запись в память; порты зовут
// эмулятор SD (sd_spi_byte), apply_mapping и обработчики плагина.
void divmmc_on_bus_write(uint32_t raw);

// Чтение порта в режиме эмуляции ПЗУ состоялось: байт ушёл на шину,
// готовить следующий. Вызывается из прерывания (port_rd_isr), только для
// портов, у которых есть ответ в таблице.
void divmmc_on_port_read(uint8_t port);

// Подставлена ли сейчас память DivMMC.
bool divmmc_mapped();

// Номер текущей страницы ОЗУ (0..15).
uint8_t divmmc_bank();

// Отметить потерянную запись. Вызывает обработчик прерывания при
// переполнении приёмной очереди: тихая потеря - страница молча
// разъехалась бы с тем, что записал процессор.
void divmmc_note_lost(uint32_t drained);

// Сколько записей потеряно с последнего сброса DivMMC. Ненулевое -
// страница разъехалась с тем, что записал процессор. Печатает
// print_bus_health.
uint32_t divmmc_lost_writes();

// Сколько раз смена подстановки из порта 0xE3 повторялась: трап
// переключил её посреди. Печатает log_task в строке divmmc:.
uint32_t divmmc_remaps();

// След переключений DivMMC с прошлого запуска (память переживает сброс
// кнопкой): напечатать и начать заново. Только при загрузке, до запуска
// Core1.
//
// Есть только при SOUNDSINTH_DIVMMC_TRACE: выключенный след не собирается
// и не печатается, 1032 байта SRAM и 440 мс загрузки остаются плате.
#if SOUNDSINTH_DIVMMC_TRACE
void divmmc_trace_report();
#endif

} // namespace bus
