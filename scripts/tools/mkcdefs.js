// Константы заголовка C++ - в #define для SDCC или .equ для sdas:
// раскладка, общая у платы и ПЗУ, живёт в одном месте.
//
//   node mkcdefs.js <заголовок.h> <выход.h | выход.inc> <префикс>
//
// inline constexpr uint32_t kRowCount = 32;  ->  #define NP_ROW_COUNT (32)
// enum Cmd : uint8_t { Open = 1, ... };      ->  #define NP_CMD_OPEN (1)
// Массивы и static_assert пропускаются.

const fs = require('fs');

const [, , src, dst, prefix] = process.argv;
if (!src || !dst || !prefix) {
    console.error('usage: mkcdefs.js <in.h> <out.h | out.inc> <prefix>');
    process.exit(1);
}

const upper = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();
const ref = (expr) => expr.replace(/\bk([A-Z]\w*)/g, (_, n) => `${prefix}_${upper(n)}`);

const asm = dst.endsWith('.inc');
const from = `Generated by mkcdefs.js from ${src.replace(/\\/g, '/')}, do not edit.`;
const out = asm ? [`;; ${from}`, ''] : [`/* ${from} */`, '#pragma once', ''];
const head = out.length;
const def = (name, value) => out.push(asm ? `${name} .equ ${value}` : `#define ${name} (${value})`);

const text = fs.readFileSync(src, 'utf8').replace(/\/\/[^\n]*/g, '');
for (const m of text.matchAll(/inline constexpr \w+ k(\w+)\s*=\s*([^;{]+);/g)) {
    def(`${prefix}_${upper(m[1])}`, ref(m[2].trim()));
}
for (const m of text.matchAll(/enum (\w+)\s*:\s*\w+\s*\{([^}]*)\}/g)) {
    const group = upper(m[1]);
    for (const e of m[2].matchAll(/(\w+)\s*=\s*([^,]+)/g)) {
        def(`${prefix}_${group}_${upper(e[1])}`, ref(e[2].trim()));
    }
}
if (out.length === head) {
    console.error(`${src}: no constants found`);
    process.exit(1);
}
fs.writeFileSync(dst, out.join('\n') + '\n');
