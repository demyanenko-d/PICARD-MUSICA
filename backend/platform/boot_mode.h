#pragma once

// Режим загрузки платы и запрос самой себе на следующую загрузку.
//
// Конфигуратор - режим загрузки, а не меню поверх работающей прошивки:
// войти и выйти можно только перезагрузкой. Иначе пришлось бы на живой
// машине разбирать и собирать заново автоматы PIO и цепочки DMA.
//
// Запрос переживает программную перезагрузку и гибнет при снятии питания:
// после сбоя питания плата в конфигураторе не застревает.
//
// Настройки в запросе не передаются. Выход из конфигуратора с сохранением
// пишет флеш сам перед перезагрузкой: машина в сбросе, второе ядро и DMA
// остановлены, и на время стирания через окно XIP никто не читает.

#include <cstdint>

namespace platform {

// Что плата должна сделать на следующей загрузке.
struct BootRequest {
    bool configurator  = false; // поднять конфигуратор, а не обычный режим
    bool saved         = false; // конфигуратор записал настройки во флеш
    bool drop_open_gui = false; // снять файл-приглашение с карты
};

// Войти в конфигуратор: взвести запрос и уйти в перезагрузку. Не
// возвращается.
void boot_reboot(const BootRequest& req);

// Записать блок настроек в блок флеша slot и перезагрузиться. Второе ядро
// выключается, DMA останавливается, прерывания гасятся; не возвращается.
// Удачная запись ставит req.saved для следующей загрузки.
void boot_reboot_saving(BootRequest req, uint32_t slot, const uint8_t* page, uint32_t bytes);

// Забрать запрос, оставленный прошлой загрузкой, и погасить его: повторная
// перезагрузка начинается с чистого листа. false - запроса нет.
bool boot_request_take(BootRequest& out);

// Прочитать тот же запрос, не гася: для решений раньше boot_request_take,
// когда настройки ещё не разобраны. false - запроса нет.
bool boot_request_peek(BootRequest& out);

// Замкнута ли перемычка режима на землю. Читается один раз при загрузке,
// до того как вывод кому-нибудь понадобится.
bool boot_jumper_closed();

// Поднят ли конфигуратор. Спрашивают подъём USB и цикл сеанса.
bool config_rom_active();

// Страница настроек: машина видит её на 0x2000, плата пишет прямо.
// nullptr - режим не поднят или платформа его не умеет.
uint8_t* config_rom_page();
uint32_t config_rom_page_bytes();

} // namespace platform
