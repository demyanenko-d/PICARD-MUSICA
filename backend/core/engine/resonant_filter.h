#pragma once

// Резонансный фильтр IT, двухполюсный, по одному на голос.
//
// Дорогая математика (два pow, деления, перевод среза в герцы) - в
// filter_compute(), раз в тик на голос; на отсчёт - три умножения с
// накоплением в filter_apply().
//
// Только ФНЧ: ФВЧ у IT задают лишь MIDI-макросы Zxx, а они не исполняются.
// Коэффициентов ModPlug нет.

#include <cstdint>

namespace soundsinth::engine {

// Коэффициенты одного голоса на тик, Q24: меньше - шумит на низком срезе.
struct FilterCoeffs {
    int32_t a0 = 0;
    int32_t b0 = 0;
    int32_t b1 = 0;
    // Числитель [1 2 1]/4 на входе рекурсии (sf2_response у filter_compute):
    // вместе с полюсами - биквад ФНЧ RBJ, как у SF2-синтезаторов.
    bool fir121 = false;
    // false - фильтровать не надо (срез открыт, резонанса нет). Вызывающий
    // обязан пропускать filter_apply() на этом голосе целиком, а не звать её
    // с нейтральными коэффициентами: экономия в том, чтобы не входить в цикл.
    bool active = false;
};

// Состояние - две ячейки на голос. Сбрасывается на триггере ноты, иначе
// новая нота начинает с хвоста предыдущей и щёлкает.
struct FilterState {
    int32_t y0 = 0;
    int32_t y1 = 0;
    int16_t x1 = 0; // два прошлых входа - только для fir121, отсчёты голоса
    int16_t x2 = 0;
};

// cutoff 0..127 (127 - открыт), resonance 0..127, env_modifier -256..+256,
// +256 - нейтраль; из сырой огибающей 0..64 - value*8 - 256.
//
// units_per_octave - делений шкалы среза на октаву: 24 у IT (срез до 5.1 кГц),
// 20 у IT с extendedFilterRange (до 10 кГц), 16 у .mid (до 20 кГц) -
// Song::filter_units_per_octave. Срез в герцах
// 110 * 2^(0.25 + cutoff*(env_modifier+256)/(units_per_octave*512)).
//
// sf2_response - вместо фильтра IT биквад ФНЧ RBJ, как в SF2-синтезаторах:
// его полюса в той же двухполюсной рекурсии плюс числитель [1 2 1]/4. Резонанс r - пик r*24/128 дБ,
// Q = 10^((r*240/128 - 3.01)/200).
FilterCoeffs filter_compute(uint8_t cutoff, uint8_t resonance, int32_t env_modifier, uint8_t units_per_octave,
                            bool sf2_response);

// Таблица среза при нейтральной огибающей под шкалу песни: filter_compute
// с этой шкалой берёт срез из таблицы, с другой - считает pow, результат
// тот же. Зовёт конструктор движка до его публикации, рендер той же таблицы
// в это время не идёт.
void filter_prepare(uint8_t units_per_octave);

// Фильтрует n отсчётов на месте. Горячий путь: три умножения с
// накоплением, сдвиг, две пересылки на отсчёт.
void filter_apply(int16_t* samples, uint32_t n, const FilterCoeffs& c, FilterState& s);

} // namespace soundsinth::engine
