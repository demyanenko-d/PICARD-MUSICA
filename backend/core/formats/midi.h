// Standard MIDI File -> Song, паттернами, как у OpenMPT: движок, длительность, конец трека и экран на ZX
// работают без доработок. Событие ложится в тик сетки, остаток - в задержку ноты; разрешение - тик,
// 10-20 мс. Инструменты - из банка: .mid несёт только номера программ.
//
// Ноты, программы и банк (CC0), velocity, темп, педаль, ударные (десятый канал, GS и XG), слои, обрыв по
// exclusiveClass. По ходу ноты: CC7/CC11, CC10, CC1 и давление канала, CC91, портаменто CC5/CC65,
// питч-бенд с диапазоном по RPN0, общая громкость из SysEx (GS и универсальная). CC120 глушит ноты
// сразу, CC123 отпускает с релизом, CC121 сбрасывает контроллеры. Сетка одна на трек.
//
// Колонка громкости: velocity на строке ноты, иначе панорама, громкость CC7/CC11, вибрато CC1; вытесненные
// velocity панорама и громкость доезжают следующей строкой. Колонка эффекта: тайминг ноты, бенд, панорама
// строки ноты, темп, посыл реверберации, скольжение; бенд абсолютный, расхождение догоняется в конце строки.

#include <cstdint>

#include "core/bank/bank_reader.h"
#include "core/model/song.h"
#include "core/formats/byte_source.h"
#include "core/memory/track_memory.h"

namespace soundsinth::formats::midi {

// Сигнатура MThd. Формат определяется по содержимому, не по имени.
bool sniff(const uint8_t* head, uint32_t bytes);

// Срезать ли паузу до первой ноты. По умолчанию да: так трек совпадает по времени с эталонным экспортом.
// Выключать для поканальных замеров на ПК: иначе каждый канал начинается своей первой нотой, и рендеры
// каналов разъезжаются на десятки секунд. Плата флаг не трогает.
void set_trim_lead_silence(bool on);

// Срезать ли тишину после последней ноты. По умолчанию да: у битого файла
// за ней стоят выключения нот с испорченными дельтами, и трек тянется
// часами. Выключать для сверки с чужим экспортом, который эту тишину
// сохраняет.
void set_trim_tail_silence(bool on);

// Навязать сетку (строк на долю, тиков на строку) вместо выбранной по
// темпу. Ноль - выбирать как обычно. Только для замеров на ПК: чем
// мельче сетка, тем точнее время и огибающие, но тем чаще работает
// секвенсор, а темп трекера обязан остаться в 32..255.
void set_forced_grid(uint8_t rows_per_beat, uint8_t ticks_per_row);

// Только для проверок на ПК: что загрузчик отдаёт конвертеру. event - на
// каждое событие строки (delay - тиков от начала строки), row_done - строка
// готова, до упаковки. row_effects - сколько раз строке выписаны темп или
// общая громкость (их пишет загрузчик, а не конвертер). nullptr - выключено.
struct ConvertTrace {
    void (*event)(void* user, uint8_t status, uint8_t d1, uint8_t d2, uint8_t delay) = nullptr;
    void (*row_done)(void* user, const soundsinth::model::PatternCell* cells)        = nullptr;
    void* user                                                                       = nullptr;
    uint32_t row_effects                                                             = 0;
    uint16_t drum_mask = 0; // ударные каналы файла (бит на канал), GS/XG SysEx учтён
};
void set_convert_trace(ConvertTrace* trace);

// Числа последней загрузки .mid; ядро само не печатает. *_known - дошла ли загрузка до этого места:
// числа нужны и когда файл не влез.
struct LoadStats {
    bool layers_known      = false; // выбор слоёв пройден: поля до notes_no_zone заполнены
    uint32_t instruments   = 0;     // инструментов песни
    uint32_t samples       = 0;     // сэмплов песни
    uint32_t keymap_ranges = 0;     // диапазонов keymap у инструментов песни
    uint32_t envelopes     = 0;     // огибающих в арене; при отказе - по ссылкам, с повторами
    uint32_t arena_bytes   = 0;     // байт резидентной арены; при отказе - верхняя оценка
    // Note-on без единого слоя не пишется вовсе.
    uint32_t notes_over_cap = 0; // номер инструмента в ячейке 9 бит: инструментам банка сверх 511 не достаётся
    uint32_t notes_no_zone = 0; // у пресета нет зоны на эту ноту и силу удара
    // Потери раскладки по каналам и колонкам.
    uint32_t steals = 0; // кража звучащего канала: все 64 заняты
    // Повтор клавиши лёг на её же канал, где прежний удар ещё доигрывал релиз:
    // так одна клавиша не копит хвосты. Тремоло рояля даёт их десятками.
    uint32_t note_restacks   = 0;
    uint32_t off_delay_lost  = 0;     // снятие без задержки внутри строки: колонка эффекта занята
    uint32_t vib_lost        = 0;     // вибрато CC1 без свободной колонки
    uint32_t tempo_deferred  = 0;     // смена темпа отложена на строку: все колонки эффекта заняты
    uint32_t tempo_dropped   = 0;     // смены темпа сверх потолка карты
    bool psram_known         = false; // паттерны упакованы: поля ниже заполнены
    uint32_t free_pages      = 0;     // страниц PSRAM сэмплам после заморозки зоны паттернов
    uint32_t samples_need_kb = 0;     // КБ PCM сэмплов песни, общий блок банка - один раз
    uint32_t patterns_kb     = 0;     // КБ зоны паттернов
    // Событий в слитом таймлайне и сколько они занимают. Потоковому пути они
    // нужны резидентно вместо паттернов, поэтому размен считается по ним.
    uint32_t events       = 0;
    uint32_t events_bytes = 0;
};
const LoadStats& last_load_stats();

// --- Строки трека заново, из файла ---
//
// Та же цепочка "события -> строка", что при загрузке: файл, курсоры,
// карта темпа и состояние конвертера живут в PSRAM и переживают её.
// Нумерация инструментов и записей сэмплов при повторе сохраняется - она
// уже запечена в песню.
//
// Нужно потоковому воспроизведению, где паттернов у .mid не будет вовсе;
// пока - чтобы сверить его с паттерным путём.

// Сколько строк в треке. 0 - .mid не загружен.
uint32_t replay_row_count();
// К началу трека. Сбрасывает состояние каналов, сохраняя нумерацию.
void replay_rewind();
// Следующая строка: ровно kMaxChannels ячеек, живут до следующего вызова.
// nullptr - строки кончились или .mid не загружен.
const soundsinth::model::PatternCell* replay_next_row();

// Строка по номеру от начала трека: ровно channels ячеек в out. Вперёд -
// догоном, назад - прогоном с начала (состояние каналов иначе не
// восстановить). За концом трека ячейки остаются как были.
void replay_row_at(uint32_t abs_row, soundsinth::model::PatternCell* out, uint8_t channels);

// Длительность трека в выходных отсчётах: посчитана при разборе, по темпу
// каждой строки. Проходом секвенсора её больше не взять - упакованных строк
// у .mid нет. 0 - .mid не загружен.
uint32_t last_total_frames();

// Сколько позиций order играется за первые frames отсчётов - для упреждения
// фоновой догрузки сэмплов. Не меньше единицы.
uint16_t order_positions_in_frames(uint32_t frames);

// metadata_only - как у остальных загрузчиков: паттерны и инструменты
// строятся, распаковка сэмплов банка в PSRAM пропускается. Для быстрого
// опроса длительности.
bool load(formats::ByteSource src, uint32_t file_length, memory::TrackMemory& mem, const bank::Bank& bank, soundsinth::model::Song& out,
          const char** error_out = nullptr, bool metadata_only = false);

// Догрузка одного сэмпла - то же место в цепочке, что load_sample_pcm у
// трекерных форматов, но источник - банк. Номер сэмпла банка лежит в
// SampleDescriptor::file_offset (у .mid поле про файл смысла не имеет).
//
// Идемпотентна: уже резидентный сэмпл возвращает успех без перекладки.
// Прогоны PCM, общие у нескольких записей, разделяются: цепочка страниц
// при игре только читается.
bool load_sample_from_bank(memory::TrackMemory& mem, const bank::Bank& bank, const soundsinth::model::Song& song, uint16_t index,
                           const char** error_out = nullptr);

} // namespace soundsinth::formats::midi
