        .module wc_cache
        .area _CODE
        .globl _wc_cache_set

;------------------------------------------------------------------------------
; void wc_cache_set(u8 value) - записать CacheConf (#2BAF).
;
; Кэш TS-Config включается поокошно и сам не сбрасывается, а сектора с
; карты WC кладёт в память DMA мимо процессора: Z80 может прочитать
; устаревшие строки. Кэш снова включает только смена турбо силами WC.
; Плагин частоту меняет записью в порт (clk.c), а wc_turbopl зовёт один
; раз, на выходе, поэтому кэш выключается один раз при входе в main().
;
; sdcccall(1): value в A.
;------------------------------------------------------------------------------
_wc_cache_set::
        push    bc
        ld      bc, #0x2BAF
        out     (c), a
        pop     bc
        ret
