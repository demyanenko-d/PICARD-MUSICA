#pragma once

// Чем сеанс трека говорит с хостом и с платой. Реализует порт.
//
// Связь с хостом не общий контракт платформы: она есть только там, где к
// плате подключена машина. На сборке без хоста этих функций не бывает
// вовсе, и требовать их от каждого порта нельзя.
//
// Ни одна из них не зовётся из прерывания: всё это цикл сеанса.

#include <cstdint>

namespace player::hal {

// --- Хост ---

// Обслужить связь: разобрать команду хоста и вооружить следующую. Можно
// звать в каждом обороте цикла.
void host_service();

// То же, плюс ожидание прерывания: для циклов, ждущих данные от хоста.
void host_service_and_wait();

// Телеметрия трека хосту: длительность и счётчики.
void host_set_file_info(uint8_t minutes, uint8_t seconds, uint16_t samples, uint16_t patterns, uint16_t instruments);

// Отпустить хост из сброса. Зовётся один раз, когда связь готова принимать:
// плата стартует дольше машины, и без удержания та обратилась бы к шине
// раньше времени.
void host_release_reset();

// Увести хост в сброс и держать: плата перезапускается, и шины для машины
// сейчас не станет. Отпускает её следующая загрузка.
void host_hold_for_reboot();

// Когда хост последний раз читал состояние связи, в микросекундах той же
// шкалы, что platform::mono_us. По давности видно, что хост ушёл из плеера
// (NMI, чужой браузер) и ждать от него данных бесполезно.
uint32_t host_last_seen_us();

// --- Потери на шине ---
//
// Записи, до обработчика не дошедшие, по двум причинам: приёмник портов не
// успел за машиной, и очередь подстановки ПЗУ переполнилась. Накопительно
// с запуска. Нужны диагностике принятого модуля: по разности видно, дыра в
// нём от нас или от машины.

uint32_t bus_lost_port_writes();
uint32_t bus_lost_rom_writes();

// --- Простой ---

// Подготовить простой: занять будильник и поставить его обработчик. Звать
// с того ядра, что крутит цикл сеанса, и до выхода машины из сброса -
// захват общего ресурса на плате гасит прерывания, а на живой шине это
// пропущенный цикл чтения.
void idle_wait_init();

// Уснуть до прерывания, но не дольше max_us. Делать нечего - ядро не должно
// выбирать команды: на плате это отнимает шину памяти у звука.
void idle_wait(uint32_t max_us);

} // namespace player::hal
