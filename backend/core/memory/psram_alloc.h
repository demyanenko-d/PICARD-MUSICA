#pragma once

// Распределитель страниц PSRAM: проси блок, расширяй, освобождай.
//
// Взамен зон с потолками и границ, которые двигали вычитанием. Кто бы ни
// пришёл за памятью - загрузчик паттернов, сэмплы, приёмник модуля GS,
// таблицы банка с карты, блочный кэш носителей, - он просит блок и
// возвращает его, когда закончил. Особых случаев нет ни у кого.
//
// Блок - НЕПРЕРЫВНЫЙ прогон страниц. Паттерны читаются по смещению и
// разрывов не терпят; сэмплы разрывов не боятся, но страницы берут
// отсюда же, чтобы владение страницей было в одном месте.
//
// Расширение: прирастить блок можно, пока страницы сразу за ним
// свободны. Это и есть обычный случай загрузчика - он в этот момент
// единственный, кто распределяет, и его блок лежит последним.

#include <cstdint>

namespace soundsinth::memory {

inline constexpr uint32_t kPsramPageBytes = 1024;
// Физический размер чипа. Хранилище трека - до всего чипа; хвосты под
// буфер GS и таблицы банка с карты отрезаются по требованию.
inline constexpr uint32_t kPsramChipBytes = 8u * 1024u * 1024u;
// Страниц на весь чип: распределение идёт по чипу, а не по зоне.
inline constexpr uint32_t kMaxSamplePageCount = kPsramChipBytes / kPsramPageBytes; // 8192

inline constexpr uint16_t kPsramNoPage = 0xffffu;

// Блок страниц. Пустой (valid() == false) - ничего не занято, освобождать
// нечего.
struct PsramBlock {
    uint16_t first = kPsramNoPage;
    uint16_t pages = 0;

    bool valid() const { return first != kPsramNoPage && pages != 0; }
    uint32_t bytes() const { return static_cast<uint32_t>(pages) * kPsramPageBytes; }
};

// Занятость страниц - битом на страницу. Слов на 8192 страницы - 256,
// то есть килобайт SRAM. Поиск прогона идёт по битам и только при
// выделении, не в горячем пути.
inline constexpr uint32_t kPsramAllocWords = (kMaxSamplePageCount + 31u) / 32u;

// Блоков, переживающих смену трека. Их немного и они наперечёт: кэш
// носителей, таблицы банка с карты, приёмник модуля GS.
inline constexpr uint32_t kPsramKeepBlocks = 8;

struct PsramAlloc {
    // Сколько страниц под распределением. Меньше kMaxSamplePageCount
    // бывает у тестов и у ключа --psram-kb.
    uint16_t page_count = 0;
    uint16_t free_pages = 0;
    // Блоков вернули повторно, и наибольшая занятая граница с последнего
    // сброса.
    //
    // Повторный возврат прибавляет свободного там, где занято, и дальше
    // распределитель раздаёт чужие страницы - порча памяти без единого
    // сообщения. Считается, а не проглатывается: чтобы вызывающего с
    // ошибкой в учёте своих блоков было видно сразу.
    //
    // Высшая точка - для травли памяти между треками: чистить весь чип
    // дорого, а выше неё ничего и не лежало.
    uint16_t double_free = 0;
    uint16_t high_water  = 0;
    // Отметок потеряно при ужатии хранилища. Не ноль - постоянный блок
    // оказался выше новой границы, и его страницы раздадут заново: кэш
    // носителей начнёт писать в данные трека.
    uint16_t kept_lost              = 0;
    uint32_t busy[kPsramAllocWords] = {};
    // Блоки, которые смена трека не отбирает. Пустая запись - свободное
    // место в списке.
    PsramBlock keep[kPsramKeepBlocks];
};

// Отдать все страницы: распределитель становится пустым на page_count
// страниц. Зовётся при создании хранилища и на смене трека.
void psram_alloc_reset(PsramAlloc& a, uint16_t page_count);

// Первый подходящий прогон. Пустой блок - столько подряд не нашлось.
PsramBlock psram_alloc(PsramAlloc& a, uint16_t pages);

// Прирастить блок на месте. false - страницы за блоком заняты или их
// нет; блок при этом не меняется, и вызывающий вправе взять новый и
// скопировать.
bool psram_alloc_extend(PsramAlloc& a, PsramBlock& block, uint16_t more);

// Отметить блок переживающим смену трека. Отмечать надо сразу после
// выделения: до отметки блок ничем не отличается от трекового. false -
// список отметок полон, и вызывающий обязан считать это отказом: иначе
// его память заберут на следующем треке.
bool psram_alloc_keep(PsramAlloc& a, const PsramBlock& block);

// Вернуть всё, кроме отмеченных блоков: их содержимое и номера страниц
// переживают вызов. page_count задаёт новый размер распределения - им
// хранилище ужимается под таблицы банка с карты и буфер GS.
//
// Отметка, не влезающая в новый размер, теряется и считается в
// kept_lost: это ошибка подъёма, потому что постоянное берут первым и
// оно лежит с краю.
void psram_alloc_release_track(PsramAlloc& a, uint16_t page_count);

// Снять отметку и освободить блок: отмеченному владельцу на разборе.
void psram_alloc_drop_kept(PsramAlloc& a, PsramBlock& block);

// Отдать хвост блока, оставив pages страниц с начала. Начало не двигается,
// поэтому смещения внутри блока переживают усечение - на этом держится
// загрузка трека: она берёт весь свободный прогон, растит данные с одного
// конца и временное с другого, а на заморозке отдаёт середину сэмплам.
// pages == 0 освобождает блок целиком, pages сверх нынешнего размера
// ничего не меняет.
void psram_alloc_shrink(PsramAlloc& a, PsramBlock& block, uint16_t pages);

// Вернуть страницы. Блок становится пустым: повторное освобождение
// ничего не портит.
void psram_alloc_free(PsramAlloc& a, PsramBlock& block);

// Сколько страниц свободно всего и сколько подряд. Второе отвечает на
// вопрос "сколько влезет одним блоком" - по нему берут остаток под
// сэмплы.
uint16_t psram_alloc_free_pages(const PsramAlloc& a);

// Занята ли страница. Для сверки учёта в тестах.
inline bool psram_alloc_page_busy(const PsramAlloc& a, uint16_t page) {
    return (a.busy[page >> 5] & (1u << (page & 31u))) != 0u;
}
uint16_t psram_alloc_largest_run(const PsramAlloc& a);

} // namespace soundsinth::memory
