;; crt0.s - старт приложения для TR-DOS.
;;
;; TR-DOS грузит код по 0x6000 и передаёт туда управление. Возврата в
;; привычном смысле нет: выходим либо перезапуском, либо обратно в TR-DOS
;; через 0x0000, и то и другое - уже забота приложения.
;;
;; РАСКЛАДКА ПАМЯТИ
;;
;;   0x4000..0x5AFF  экран (страница 5, видна всегда)
;;   0x5B00..0x5FFF  системные переменные TR-DOS, не трогать
;;   0x6000          сюда грузимся: код, данные, за ними знакогенератор
;;                   (область _FONT, 2 КБ)
;;   0xB600..0xB700  таблица векторов IM 2 (её ставит z80_fw)
;;   0xB7B7          переход на обработчик
;;   0xBF00          стек, растёт вниз до перехода на 0xB7B9
;;   0xC000..0xFFFF  окно страниц: отрезки файлов и таблица каталога
;;
;; Код, данные и шрифт обязаны кончаться ниже 0xB600: таблицу векторов
;; прерываний z80_fw пишет поверх того, что там окажется.

        .module crt0
        .globl  _main
        .globl  l__INITIALIZER
        .globl  s__INITIALIZED
        .globl  s__INITIALIZER
        .globl  s__DATA
        .globl  l__DATA

STACK   .equ    0xBF00

;; Переход на запуск обязан лежать первым байтом по адресу загрузки:
;; TR-DOS передаёт управление прямо туда. Поэтому он и стоит в _CODE, а
;; crt0 линкуется первым - тогда его кусок кода и оказывается в начале.
;;
;; Отдельная абсолютная область с .org не годится: компоновщик уводит её
;; по своему адресу, а на 0x6000 ложится чужой код.
        .area   _CODE
        jp      init

;; Порядок областей задаёт раскладку. Инициализированные данные
;; копируются, потому что образ на диске один, а память под них другая.
        .area   _HOME
        .area   _INITIALIZER
        .area   _GSINIT
        .area   _GSFINAL

        .area   _DATA
        .area   _INITIALIZED
        .area   _BSEG
        .area   _BSS
        .area   _HEAP

        .area   _GSINIT
init:
        di
        ld      sp, #STACK

        ;; Обнулить неинициализированные данные: библиотека ждёт нулей в
        ;; счётчиках, указателях колец и флагах, а TR-DOS оставляет мусор.
        ld      hl, #s__DATA
        ld      de, #s__DATA + 1
        ld      bc, #l__DATA - 1
        ld      a, b
        or      a, c
        jr      z, crt0_no_data
        ld      (hl), #0
        ldir
crt0_no_data:

        ;; Перенести начальные значения глобальных переменных Си.
        ld      bc, #l__INITIALIZER
        ld      a, b
        or      a, c
        jr      z, crt0_no_init
        ld      de, #s__INITIALIZED
        ld      hl, #s__INITIALIZER
        ldir
crt0_no_init:

        call    _main

        ;; main() вернулся - обработчик из ПЗУ и уход в TR-DOS холодным
        ;; стартом.
        di
        im      1
        ld      a, #0x3F
        ld      i, a
        ei
        rst     0

        .area   _GSFINAL
        ret
