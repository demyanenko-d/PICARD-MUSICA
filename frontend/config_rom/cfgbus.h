/*
 * cfgbus.h - разговор конфигуратора с платой.
 *
 * Команд всего две. Страницу плата заполняет сама, до того как отпустит
 * машину из сброса, поэтому отдельной команды "прочитать" нет.
 *
 * Своя, а не bus_client: тому нужна сессия загрузки файла, телеметрия и
 * окна чтения - здесь из этого не нужно ничего.
 */

#ifndef CONFIG_ROM_CFGBUS_H
#define CONFIG_ROM_CFGBUS_H

#include "../common/types.h"

/* Чем кончить работу: должно совпадать с ConfigExit платы. */
#define CFG_EXIT_DISCARD 1
#define CFG_EXIT_SAVE 2
#define CFG_EXIT_REENTER 3

/**
 * Дождаться платы: она стартует дольше машины. TRUE - страница на месте и
 * пригодна.
 */
bool_t cfg_wait_board(void);

/**
 * Отдать плате правленые значения и забрать пересчитанные. Плата приводит
 * их к допустимым и обновляет маску доступных полей.
 *
 * TRUE - значения приняты. FALSE - плата не ответила или отвергла
 * страницу; экран перерисовывать не по чему.
 */
bool_t cfg_refresh(void);

/** Уйти в перезагрузку. Не возвращается: плата уводит машину в сброс. */
void cfg_exit(u8 how);

#endif
