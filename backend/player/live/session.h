#pragma once

// Живой MIDI на плате: поток с отвода порта A AY становится песней, которую
// играет обычный движок.
//
// Режим включается сам, по осмысленному потоку, и выключается по тишине:
// либо пауза, либо со Спектрума запустили другое приложение. Одновременно с
// треком из файла живой режим не работает - это разные приложения.
//
// Кто что делает: задача рендера (live_row) разбирает отвод, ставит события
// в очередь с упреждением и отдаёт движку строку на тик; app_task (poll)
// ищет поток, собирает и сносит сеанс; цикл Core1 тянет из флеша заказанные
// сэмплы - там их не вытесняет рендер.

#include <cstdint>

#include "core/engine/tracker_engine.h"

namespace player::live {

// Идёт ли живой режим.
bool session_active();

// Строка живой песни на тик - источник строк движка (задача рендера).
const soundsinth::model::PatternCell* live_row(void* user);

// Живая песня поверх памяти трека и флеш-банка; движок собирает вызывающий.
// false - не с чем играть (нет банка) или память занята.
bool session_begin(uint32_t now_ms);

// Конец живого режима: песня и счётчики сбрасываются, память трека остаётся
// вызывающему.
void session_end();

// Пришёл ли осмысленный поток: разбирает отвод, пока режим выключен.
// true - пора включать живой режим.
bool stream_started(uint32_t now_ms);

// --- Передача памяти трека живому режиму ---
//
// То же рукопожатие, что у эмуляции GS, и ради того же: память трека
// режет тот, кто её наполняет. Core0 только просит, Core1 на своём
// проходе закрывает сеанс, гасит фоновую догрузку и подтверждает. Без этого
// begin() пересобирает список страниц под выделяющим.
void request_track_memory();
bool wants_track_memory();
void grant_track_memory();
bool track_memory_granted();

// Сколько миллисекунд не было событий (для таймаута выхода).
uint32_t silent_ms(uint32_t now_ms);

// Разобрать отвод в очередь, пока режим ещё не включён. Для долгих
// пауз на входе в режим: снос движка идёт десятки миллисекунд, и всё
// это время кольцо не разбирает никто. После включения режима ничего
// не делает: там очередь пишет тик рендера, а двух писателей она не держит.
void pump_stream(uint32_t now_ms);

// Тянет из флеша заказанный сэмпл и возвращает отданные записи. Зовётся из
// цикла Core1, рядом с фоновой догрузкой трека: на Core0 задача рендера
// приоритетом выше и оставляет подгрузке около десятой доли времени: чтение
// в 12 мс там растягивается до 122, и нота молчит. За проход - один
// сэмпл, между ними цикл обслуживает шину. true - что-то сделано.
bool serve_requests();

// Строка счётчиков живого режима в лог.
void session_log_stats();

// Разбор молчащих нот: движок считает их и держит номера сэмплов последних.
// Живой сеанс поднимает историю записи и говорит, почему PCM не оказалось -
// не успели прочитать или уже выбросили. Звать из опроса живого режима ДО
// подгрузки: иначе дочитанное через миллисекунды после ноты выглядит как
// успевшее. Разбор берёт номера сам, по счётчику движка.
void note_missing(const soundsinth::engine::TrackerEngine& engine);

// Указатель, который передаётся live_row как user.
void* row_user();

} // namespace player::live
