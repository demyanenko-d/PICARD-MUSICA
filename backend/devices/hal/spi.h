#pragma once

// Шина SPI под карту памяти: всё платформенное, что нужно протоколу.
// Определяет порт.
//
// Не из ISR: обмен блокирующий, сектор на полной скорости - около 200 мкс.
// Пересечений границы на сектор около двух десятков: команда, ответ, токен
// и один блочный обмен на 512 байт.

#include <cstdint>

namespace devices::hal {

// Поднять выводы и блок SPI на частоту hz; вернуть фактическую. Делитель
// целый, а режиму опознания карты нужны 100..400 кГц: промах даёт
// неотвечающую карту, по виду неотличимую от обрыва.
//
// Подтяжка на входе обязательна: шина SD требует её на CMD и DAT0-DAT3, на
// готовых модулях резисторы распаяны, на голом слоте нет. Без неё линия в
// покое читается нулём при исправной карте, и "карты нет" не отличить.
//
// CS ведёт порт обычным выводом, а не аппаратным SS: транзакция SD - это
// команда, ответ и блок при удерживаемом CS, а аппаратный SS снимается
// после каждого слова.
uint32_t spi_open(uint32_t hz);

// Сменить частоту; вернуть фактическую.
uint32_t spi_set_hz(uint32_t hz);

// Выбор карты: true - CS опущен.
void spi_select(bool on);

// Обмен одним байтом.
uint8_t spi_xfer(uint8_t out);

// Блок: на чтении выход держится idle, на записи выдаётся src.
void spi_read(uint8_t idle, uint8_t* dst, uint32_t n);
void spi_write(const uint8_t* src, uint32_t n);

} // namespace devices::hal
