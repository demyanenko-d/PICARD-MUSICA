;; irq.s - кадровое прерывание в режиме IM 2 со своим обработчиком.
;;
;; Не IM 1, потому что там управление уходит в ПЗУ по 0x0038: свой опрос
;; клавиатуры, часы, мигание курсора, плюс порча системных переменных.
;;
;; В IM 2 процессор берёт вектор из ячейки (I << 8) | шина. Что
;; на шине - зависит от железа, и на Спектруме там обычно 0xFF, но
;; полагаться на это нельзя. Поэтому кладут таблицу из 257 одинаковых байт:
;; тогда любой байт с шины даёт одно и то же слово. 257, а не 256, потому
;; что вектор читается двумя байтами подряд и последний может уехать за
;; границу таблицы.
;;
;; Значение в таблице выбрано так, чтобы адрес перехода лежал сразу за ней
;; и никуда больше не попадал:
;;
;;     таблица 0xB600..0xB700, вся забита 0xB7  ->  вектор 0xB7B7
;;
;; Таблица и переход обязаны лежать в памяти, которая видна всегда: прервать
;; могут в тот момент, когда в окне 0xC000 чужая страница. Страница 2
;; (0x8000..0xBFFF) на 128K не переключается - там и лежим.

        .module irq
        .globl  _fw_irq_init
        .globl  _fw_irq_stop
        .globl  _fw_ticks
        .globl  _fw_wait_frames

        .globl  _fw_kbd_scan

IRQ_TABLE .equ  0xB600
IRQ_FILL  .equ  0xB7
IRQ_JUMP  .equ  0xB7B7

        .area   _DATA

_fw_ticks::     .ds     2       ; сколько кадров прошло с запуска

        .area   _CODE

;; Поставить свой обработчик и разрешить прерывания.
_fw_irq_init::
        di

        ld      hl, #0
        ld      (_fw_ticks), hl

        ld      hl, #IRQ_TABLE
        ld      (hl), #IRQ_FILL
        ld      de, #IRQ_TABLE+1
        ld      bc, #256
        ldir

        ld      a, #0xC3        ; JP nn
        ld      (IRQ_JUMP), a
        ld      hl, #fw_isr
        ld      (IRQ_JUMP+1), hl

        ld      a, #IRQ_TABLE >> 8
        ld      i, a
        im      2
        ei
        ret

;; Вернуть машину как было: обработчик из ПЗУ.
;;
;; Обязательно перед выходом в TR-DOS или бейсик: иначе первое же
;; прерывание уйдёт по нашему адресу, где будет что угодно.
_fw_irq_stop::
        di
        im      1
        ld      a, #0x3F        ; ПЗУ ждёт I именно таким
        ld      i, a
        ei
        ret

;; -- Обработчик --
;;
;; Считает кадры и опрашивает клавиатуру, обе вещи короткие и без
;; ожиданий. Карта, экран и разбор каталога - в основном потоке.
;;
;; Сохраняем то, что портит опрос: A, BC, DE, HL. Альтернативный набор и
;; индексные он не трогает.
fw_isr:
        push    af
        push    bc
        push    de
        push    hl

        ld      hl, (_fw_ticks)
        inc     hl
        ld      (_fw_ticks), hl

        call    _fw_kbd_scan

        pop     hl
        pop     de
        pop     bc
        pop     af
        ei
        reti

;; Подождать A кадров, через HALT.
_fw_wait_frames::
        or      a
        ret     z
        ld      b, a
fw_wait_loop:
        halt
        djnz    fw_wait_loop
        ret
