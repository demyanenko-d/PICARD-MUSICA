#pragma once

// Журнал кольцами: реализация platform/log.h поверх debug_ring.
//
// debug_log() в консоль не пишет - кладёт строку в кольцо своего ядра и
// возвращается. Кольца разбирает один потребитель, обычно задача логгера:
// блокирующая выдача держала бы ядро миллисекундами, а на втором в это
// время стоит обслуживание шины.
//
// Кольцо на ядро, без блокировок и без маскирования прерываний. Строки
// ядер выходят с небольшой перестановкой, внутри ядра порядок строгий.
// Переполнение отбрасывает строку целиком, а не печатает половину: число
// потерянных выводится отдельно, тихая потеря хуже блокировки.
//
// От порта нужны пять мелочей - они ниже; всё остальное здесь.

#include <cstdint>

namespace platform {

// --- Что даёт порт ---

// Байт в консоль, если она принимает; освобождения не ждать. false - не
// взят.
bool log_put(uint8_t b);

// Строка в консоль с ожиданием. Только прямой режим: старт до потребителя
// и обработчики отказа.
void log_put_blocking(const char* msg);

// Дождаться, пока консоль примет хотя бы байт. Только аварийная выгрузка.
void log_wait_ready();

// Вызов идёт из обработчика прерывания. Такие строки не пишутся: писатель
// того же ядра мог быть прерван посреди своей.
bool in_isr();

// Номер ядра: у каждого своё кольцо.
uint32_t core_id();

// Запретить и разрешить переключение задач своего ядра. Между ними идёт
// копирование строки в кольцо: push не реентерабелен, а на ядре с
// планировщиком пишут несколько задач. Прерывания не маскируются.
void log_writer_lock();
void log_writer_unlock();

// --- Что даёт этот файл ---

// Проход потребителя: выгрести не больше max_bytes и доложить о
// собственных потерях, если их число изменилось. Возвращает, осталось ли
// что выдать - по нему выбирается срок следующего прохода. По выданному
// решать нельзя: при полном приёмнике выдано 0, а кольцо не пусто.
//
// Потери печатаются через кольцо, как прочие строки: прямая печать встала
// бы в середину недосланной строки.
bool log_service(uint32_t max_bytes);

// Выгрести накопленное в консоль, не больше max_bytes за вызов. Зовёт
// только потребитель. Возвращает число выданных байт.
uint32_t log_drain(uint32_t max_bytes);

// Осталось ли что выдать: строка в кольце или недосланный хвост.
bool log_pending();

// Отказ на ядре потребителя: выгрузить оба кольца, ожидая консоль. Только
// из обработчика отказа.
void log_flush_blocking();

// Печатать прямо в консоль блокирующим вызовом: потребителя ещё или уже
// нет. Так работает старт и обработчики отказа.
void log_go_direct();
// Печатать через кольца: строки забирает потребитель.
void log_use_rings();

// Строк потеряно на переполнении колец, по обоим ядрам.
uint32_t log_dropped();
// Строк не влезло в буфер debug_logf: виноват короткий буфер, а не
// занятость, и лечится это по-другому.
uint32_t log_truncated();
// Вызовов debug_log из обработчика прерывания: такие строки не пишутся.
uint32_t log_isr_calls();

} // namespace platform
