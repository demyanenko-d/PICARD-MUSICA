#pragma once

// Сигналы машине: сброс и немаскируемое прерывание. Реализует порт.
//
// Это не клавиши: в матрице их нет ни в одной раскладке, и добраться до
// них с эмулируемой клавиатуры нельзя в принципе. Отдельный контракт
// нужен потому, что линиями владеет плата, а повод их дёрнуть приходит из
// платформонезависимого слоя.
//
// Вызов только просит подать сигнал и сразу возвращается: длительность
// импульса и отпускание линии - дело порта. Ждать здесь нельзя, зовут из
// цикла, который обслуживает и другие устройства.

namespace devices::hal {

// Сброс машины. Линию держит плата и отпускает сама.
void host_reset_request();

// Немаскируемое прерывание: фронт вниз. Процессор защёлкивает его сам,
// поэтому длительность важна только как нижняя граница.
void host_nmi_request();

// Полный сброс: перезапуск платы вместе с машиной.
//
// Отличие от host_reset_request в том, что сбрасывается НАША сторона.
// Эмуляторы устройств состояние машины не отслеживают: после её сброса
// DivMMC остаётся с прежним банком и подстановкой, протокол - с
// незакрытым сеансом, и машина находит железо не в том виде, в каком оно
// бывает после включения. Загрузка платы приводит в исходное всё разом,
// и это дешевле и надёжнее, чем сбрасывать каждый эмулятор по отдельности
// под работающей машиной.
//
// Играющий трек при этом теряется - на то и полный сброс.
void host_hard_reset_request();

} // namespace devices::hal
