#pragma once

// Z-Controller, которым плата притворяется для хоста.
//
// Два порта, оба ведут к эмулятору карты:
//   0x57  запись - отдать байт карте (MOSI)
//         чтение - ответ карты на предыдущий обмен; сразу после чтения
//                  запускается холостой обмен (0xFF), его ответ получит
//                  следующее чтение
//   0x77  запись - бит 1 это SSEL: 0 выбирает карту, 1 снимает выбор
//         чтение - бит 1: 0 карта на месте, 1 карты нет

#include <cstdint>

namespace devices::zcontroller {

// Зарегистрировать порты. Звать после того, как шина готова принимать
// обработчики, и после storage_init().
//
// emulator_up - эмулятор карты уже подняли (в режиме DivMMC это делает он):
// повторный подъём сбросил бы чужое состояние.

void zcontroller_init(bool emulator_up);

} // namespace devices::zcontroller
