#pragma once

// Межъядерная поверхность звука и загрузки. Кроме неё Core0 читает счётчики
// шины и карты только для лога (log_task).
//
// Раскладка по ядрам: Core1 - шина и загрузка (без ОС: PIO, DMA, ISR,
// session_orchestrator_run), Core0 - звук (FreeRTOS: app_task,
// RenderTask, TrackerEngine).
//
// Загрузка и разбор трека (BusByteSource + formats::*::load()) целиком на
// Core1: разбор ждёт байты, их подаёт обработчик шины на том же ядре,
// блокирующая синхронизация между ядрами не нужна.
//
// Core1 дописывает сэмплы, пока Core0 играет (прогрессивная загрузка).
// Общение без блокировок, атомиками, без очередей и мьютексов.
//
// g_track_memory/g_song глобальные (не куча и не стек):
// (1) TrackMemory - десятки килобайт (буферы упаковки и загрузчика,
//     PsramStore::page_next[8192] по 2 байта = 16 КБ), больше стека
//     Core1 и стека app_task;
// (2) нужна по адресу с обоих ядер, без указателя из кучи, который
//     пришлось бы синхронизировать.
//
// track_memory_create(g_track_memory) вызывается один раз в main() до
// multicore_launch_core1(); дальше все загрузки используют только
// track_memory_reset_for_new_track.

#include <atomic>
#include <cstdint>

#include "core/bank/bank_reader.h"
#include "core/model/song.h"
#include "core/memory/track_memory.h"

namespace shared {

extern soundsinth::memory::TrackMemory g_track_memory;

// Банк инструментов для .mid: вид на таблицы во флеше (по XIP) или в
// хвосте PSRAM (банк с карты), без копирования. Таблицы после открытия не
// пишет никто, читают оба ядра. bank_make_resident - только Core1: он
// зовёт обслуживание шины и карты этого ядра (g_bank.serve), страницы
// выделяет один писатель.
extern soundsinth::bank::Bank g_bank;
// Банк во флеше - для живого MIDI: сэмплы подгружаются в PSRAM отсюда, не
// с карты. Открывается при старте всегда, независимо от g_bank.
extern soundsinth::bank::Bank g_flash_bank;
extern soundsinth::model::Song g_song;

// 0 - ничего не загружено. Увеличивает Core1 (загрузка и эмуляция GS)
// после записи песни и памяти трека; Core0 (app_task) видит новое значение
// и собирает TrackerEngine поверх готовых g_song/g_track_memory. Хвост
// сэмплов может быть ещё не загружен - такие ноты молчат.
extern std::atomic<uint32_t> g_song_generation;

// Поколение, из песни которого движок собирать нельзя: её бросил сброс
// хоста или переписывает загрузка. Пишет основной поток Core1 - on_reset
// перед просьбой о сносе и track_load_begin после ожидания сноса; app_task
// такое поколение пропускает. Без него поколение, поднятое перед сбросом
// или отказом загрузки, собиралось бы на следующем обороте поверх
// брошенной или недогруженной песни.
extern std::atomic<uint32_t> g_stale_generation;

// Для строки застоя на Core1. Пишет только app_task: обороты цикла (раз в
// 50 мс) и поколение, из которого собран движок. Стоят обороты - стоит
// Core0 (или задачу не пускает RenderTask); поколение собранного отстаёт
// от g_song_generation - движок не собран.
extern std::atomic<uint32_t> g_app_task_loops;
extern std::atomic<uint32_t> g_engine_generation;

// Жив ли Core1 - для log_task: обороты основного цикла и обслуживания без ожидания (пишет
// только основной поток Core1) и фаза, в которой он сейчас. Стоящий
// счётчик с фазой называет место, где Core1 ждёт: окно от хоста (Load),
// снос движка на Core0 (TeardownWait), разбор модуля GS без обслуживания шины.
enum class Core1Phase : uint8_t { Loop, Load, TeardownWait, GsModule };

// Где именно в витке находится Core1. Нужно сторожу живости: фаза
// говорит "в цикле", а шаг - на чём именно встало.
enum class Core1Step : uint8_t {
    GsPoll,
    Watch,
    HostService,
    SdTask,
    UsbTask,
    Transport,
    LiveServe,
    PlanLoad,
    IdleWait,
    RunSession,
};
extern std::atomic<Core1Step> g_core1_step;
extern std::atomic<uint32_t> g_core1_loops;
extern std::atomic<Core1Phase> g_core1_phase;
// Кадр конца трека для затухания шины (0 - нет). Пишет Core1 до
// g_song_generation (release), читает Core0 после неё.
extern std::atomic<uint32_t> g_track_end_frame;

// Пишет Core0 (TrackerEngine::elapsed_frames()), читает Core1
// (периодический set_position()).
extern std::atomic<uint32_t> g_playback_frames;

// Пишет Core1: on_reset() на каждый 0x01 с шины безусловно (ESC без
// выбора нового трека тоже должен заглушить звук) и загрузка, которой
// мешает живой движок (try_stop_engine_for_load). Читает и сбрасывает
// Core0 (app_task): остановить текущий TrackerEngine/RenderTask - либо
// просто сброс, либо сейчас начнётся новая сессия поверх свежих
// g_song/g_track_memory.
extern std::atomic<bool> g_teardown_requested;

// Пишет Core0 (app_task): true, когда TrackerEngine::song_ended() стал
// true. Читает Core1: телеметрия позиции (0x87) с playback_state = 2.
// Сбрасывает track_load_begin, когда движок снят, иначе флаг прошлого
// трека перенёсся бы на следующий.
extern std::atomic<bool> g_song_ended;

// Пишет Core1: true, когда трек доиграл - g_song_ended или отыграна
// вычисленная длительность одного прохода. Читает Core0 (app_task) и
// глушит выход.
//
// Движок на другом ядре, остановить его отсюда нельзя; заглушить синк
// достаточно.
//
// Сбрасывает track_load_begin, как g_song_ended.
extern std::atomic<bool> g_playback_finished;

// Пауза по команде хоста: ставит Core1 (разобрал команду), исполняет Core0
// (задача рендера). Выход гаснет затуханием, дальше источники не зовутся -
// позиция стоит. Сбрасывается вместе с прочим при смене трека.
extern std::atomic<bool> g_playback_paused;

// Перемотка вперёд: на сколько выходных отсчётов уехать, 0 - не просили.
// Ставит Core1 (команда хоста), исполняет Core0. Сама прокрутка тиков долгая и
// движок трогает, поэтому идёт только под паузой: пока выход погашен,
// микшер источники не зовёт, и рендер движка не касается.
extern std::atomic<uint32_t> g_seek_frames;

// --- Прогрессивная загрузка: что Core0 (звук) сообщает Core1
// (загрузка). Публикуется раз в тик из TickObserver
// (publish_tick_state). Нужно для вытеснения сэмплов из PSRAM
// под играющий звук.

// Текущая позиция в order-листе. Вместе с last_use_order_pos
// планировщика отвечает, отыграл ли сэмпл.
extern std::atomic<uint16_t> g_order_pos;

// Текущая строка паттерна, для команд #61/#62 эмуляции General Sound.
// Гонка безобидна: опоздание на тик софт не различит.
extern std::atomic<uint16_t> g_row_pos;

// Жив ли движок: взводится до создания TrackerEngine, снимается после
// его сноса. По нему загрузка ждёт сноса (track_load_begin): сброс с шины
// приходит заранее, Core0 обрабатывает его не мгновенно, а у эмуляции GS
// отдельного сброса нет вовсе. Без ожидания разбор переписывал бы Song и
// память трека под играющим движком.
extern std::atomic<bool> g_engine_alive;

// Идёт загрузка трека, движок собирать нельзя. Взводит track_load_begin,
// снимает track_load_end.
//
// Без запрета движок, собранный посреди загрузки, играл бы из ещё не
// загруженной песни, а разбор переписывал бы Song и страницы PSRAM под
// ним: голос уходит по мёртвому указателю (отказ шины в voice_render на
// чтении страницы сэмпла).
extern std::atomic<bool> g_load_in_progress;

// Начать загрузку трека в память, которую читает движок: запретить сборку
// нового и дождаться сноса текущего. pump зовётся на каждом круге
// ожидания - обслуживать шину, пока Core0 снимает движок (может быть
// nullptr). Снять запрет - track_load_end(), и после отказа тоже; движок
// соберётся по следующей смене поколения.
//
// Порядок как у двух флагов Деккера, всё seq_cst: здесь запись
// g_load_in_progress, потом чтение g_engine_alive; в app_task запись
// g_engine_alive, потом чтение g_load_in_progress. Либо Core0 увидит
// запрет и не соберёт движок, либо здесь увидим живой движок и дождёмся
// сноса.
void track_load_begin(void (*pump)(void*), void* user);
void track_load_end();

// Один шаг того же рукопожатия, без ожидания: запретить сборку и, если
// движок жив, попросить Core0 снести его. true - движок снят и не
// соберётся, пока запрет стоит. Для опроса из цикла (резерв GS);
// track_load_begin зовёт его в своём цикле ожидания.
bool try_stop_engine_for_load();

// Сторона Core0 того же рукопожатия: объявить движок живым и проверить
// запрет загрузки. false - загрузка идёт, движок снова не живой, собирать
// нельзя.
bool try_mark_engine_alive();

// Трек в памяти готов играть: счётчик воспроизведения с нуля, конец трека
// (0 - конец задаёт плеер GS), смена поколения - по ней Core0 соберёт
// движок. Основной поток Core1, после track_load_end; не из обработчиков.
//
// Счётчик обнуляется здесь: до сборки нового движка в нём значение прошлого
// трека, и "доиграл" сработал бы сразу. До track_load_begin нельзя: Core0 до
// сноса движка допишет старое значение.
void publish_loaded_track(uint32_t end_frame);

// Битовая карта "сэмпл держит живой голос сейчас", включая хвосты NNA.
// Такие сэмплы вытеснять нельзя: Voice держит свои first_page/page, и
// удаление записи из каталога голос не остановит - он пойдёт по
// освобождённым и, возможно, переиспользованным страницам.
//
// Сэмплы с индексом >= kSamplesInUseBits в карту не попадают; читатель
// обязан считать их всегда занятыми.
inline constexpr uint16_t kSamplesInUseBits  = 512;
inline constexpr uint16_t kSamplesInUseWords = kSamplesInUseBits / 32;
extern std::atomic<uint32_t> g_samples_in_use[kSamplesInUseWords];

// true, пока Core1 догружает сэмпл фоном под играющий звук. Для
// диагностики: отличить две причины призвука -
//   (а) сэмплы грузятся битыми (шум привязан к ноте и не зависит от
//       догрузки);
//   (б) Core1 конкурирует с Core0 за QMI/PSRAM и рендер не успевает
//       (заминки ровно в окне догрузки).
// Пишет Core1, читает Core0.
extern std::atomic<bool> g_background_loading;

// --- Нагрузка Core0, для телеметрии на экране плагина ---
//
// Оба счётчика монотонные и не сбрасываются: сброс с другого ядра - гонка.
// Читатель (Core1) держит прошлые значения и считает разницу, период
// усреднения задаёт он.
//
// g_render_busy_us - сколько микросекунд Core0 считал звук (только
// render(), без ожидания буфера). Делённое на прошедшее время - доля ядра
// на аудио.
//
// g_voice_count_* - статистика полифонии по тикам, средние считает
// читатель.
//
// Пишет Core0, читает Core1. Писатель один - relaxed load и store; у
// g_voice_count_peak писателей два (Core1 обнуляет exchange), поэтому RMW.
extern std::atomic<uint32_t> g_render_busy_us;
extern std::atomic<uint32_t> g_voice_count_ticks;

// Сумма квадратов числа голосов по тикам, из неё квадратичное среднее:
// лежит между средним и максимумом и тяжелее весит всплески. Монотонная.
extern std::atomic<uint32_t> g_voice_count_sq_sum;

// Пик за период. Единственный сбрасываемый счётчик: сбрасывает читатель
// (Core1) через exchange(0). Если Core0 поднимет значение между чтением
// и обнулением, потеряется пик одного тика - для цифры на экране
// допустимо.
extern std::atomic<uint32_t> g_voice_count_peak;

// Насколько движок режет голоса из-за перегрузки: 0 - не режет, 1..3 -
// режет, насколько просела полифония. Хост показывает столько же
// восклицательных знаков после числа голосов.
//
// Считает Core0 (видит бюджет и число сброшенных), читает Core1 при
// отправке телеметрии. Уровень держится пару секунд после последнего
// сброса, иначе индикатор мигал бы на каждой паузе.
inline constexpr uint32_t kVoiceCullLevelMax = 3;
extern std::atomic<uint32_t> g_voice_cull_level;
} // namespace shared
