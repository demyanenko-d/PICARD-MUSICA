// Ресурсы экрана приложения TR-DOS в исходник ассемблера.
//
// node mkui.js <res dir> <out.s>
//   deck.scr    -> _ui_deck: экран 6912 байт, сжатый PackBits (байт n < 0x80 -
//                  n + 1 байт как есть; n >= 0x80 - следующий байт n - 0x7F раз)
//   font6.bin   -> _fw_font: CP866 6x8, 8 байт на символ на входе; на выходе
//                  по строкам: страница 256 байт на строку глифа 1..7, код
//                  символа - младший байт адреса. Строка 0 пустая и не
//                  хранится, биты 2..0 (столбцы 5..7) сброшены: вывод
//                  ui6.s складывает символы без маски. Область _FONT
//                  ставится на границу 256 байт при компоновке.
//   seg7.bin    -> _ui_seg7: 7-сегментные 0-9 : /, по 15 байт
//   digits4.bin -> _ui_digits4: цифры 4x8 0-9 : /, по 6 байт
//   repeat.bin  -> _ui_repeat: значки повтора 16x8 (всё, один, шафл, раз), по 16 байт
'use strict';
const fs = require('fs');
const path = require('path');
const [, , resDir, outPath] = process.argv;
const rd = n => fs.readFileSync(path.join(resDir, n));

function packbits(d) {
  const out = [];
  let i = 0;
  while (i < d.length) {
    let run = 1;
    while (i + run < d.length && d[i + run] === d[i] && run < 128) run++;
    if (run >= 3) { out.push(0x7f + run, d[i]); i += run; continue; }
    const start = i;
    while (i < d.length && i - start < 128) {
      let r = 1;
      while (i + r < d.length && d[i + r] === d[i] && r < 3) r++;
      if (r >= 3) break;
      i++;
    }
    out.push(i - start - 1, ...d.subarray(start, i));
  }
  return out;
}

const deck = rd('deck.scr');
if (deck.length !== 6912) throw new Error('deck.scr must be 6912 bytes');
const db = (label, bytes) => {
  let s = `${label}::\n`;
  for (let i = 0; i < bytes.length; i += 16) s += '        .db ' + [...bytes.slice(i, i + 16)].map(b => '0x' + b.toString(16).padStart(2, '0')).join(', ') + '\n';
  return s;
};
const deckPacked = packbits(deck);
let s = ';; Generated by scripts/tools/mkui.js from frontend/trdos/res. Do not edit.\n';
s += '        .module ui_res\n        .area   _CODE\n';
s += db('_ui_deck', deckPacked);
s += db('_ui_seg7', rd('seg7.bin'));
s += db('_ui_digits4', rd('digits4.bin'));
s += db('_ui_repeat', rd('repeat.bin'));
s += '        .area   _FONT\n';
const font = rd('font6.bin');
if (font.length !== 2048) throw new Error('font6.bin must be 2048 bytes');
const rows = Buffer.alloc(7 * 256);
for (let l = 0; l < 7; l++) for (let c = 0; c < 256; c++) rows[l * 256 + c] = font[c * 8 + l + 1] & 0xf8;
s += db('_fw_font', rows);
fs.writeFileSync(outPath, s);
console.log(`ui_res: deck ${deckPacked.length} B packed`);
