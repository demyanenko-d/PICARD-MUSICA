#pragma once

// Настройки текстом: разбор файла с карты и обратная запись с
// комментариями.
//
// Формат построчный:
//
//   ; строка целиком комментарий
//   KEY=VALUE
//
// Пробелы и непечатные знаки внутри строки отбрасываются, имя ключа
// сверяется без учёта регистра. Неизвестный ключ и неразборчивое значение
// пропускаются, остальные строки применяются: файл с опечаткой не отменяет
// весь свой смысл.

#include <cstdint>

#include "core/config/config.h"

namespace soundsinth::config {

struct IniResult {
    uint32_t applied = 0; // сколько ключей легло в настройки
    uint32_t unknown = 0; // имя не из таблицы
    uint32_t bad     = 0; // имя знакомо, значение не разобрано
};

// Разобрать текст поверх уже заполненных настроек: чего в файле нет,
// остаётся прежним.
IniResult ini_parse(const char* text, uint32_t len, Settings& s);

// Записать настройки с комментариями. Возвращает длину без завершающего
// нуля; при нехватке места - сколько понадобилось бы, а out не трогается.
uint32_t ini_render(const Settings& s, char* out, uint32_t cap);

// Запас на файл целиком. Умолчания занимают около четырёх килобайт, почти
// всё - комментарии; длину печатает тест. Не влезший файл не сохраняется
// вовсе, поэтому запас держится кратным.
inline constexpr uint32_t kIniMaxBytes = 6144;

} // namespace soundsinth::config
