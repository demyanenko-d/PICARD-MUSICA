// Банк инструментов .mid: где его искать и куда подключить.
//
// Банков два и они не взаимозаменяемы. Во флеше банк лежит всегда: живой
// MIDI подгружает сэмплы только из него, и ждать карту там нельзя. Файлу
// на карте отдаётся предпочтение для треков: он больше и меняется без
// перепрошивки.

#include <cstdint>

namespace player {

// Открыть оба банка и подключить файловый к загрузчику сеанса. Флеш-банк
// порт отдаёт указателем: где он лежит и сколько под него отведено, знает
// только раскладка прошивки. Без банка .mid отвергается с причиной,
// остальное работает. Звать после того, как поднята память трека.
//
// pump зовётся между куска́ми чтения таблиц с карты (сотни миллисекунд на
// полный банк): им качают то, что иначе простоит всё это время. Нужен
// вызывающему, который успел поднять что-то асинхронное - например
// USB-хост: без витка перечисление не двигается, и клавиатура ждёт банк.
void open_banks(const uint8_t* flash_blob, uint32_t flash_bytes, void (*pump)() = nullptr);

} // namespace player
