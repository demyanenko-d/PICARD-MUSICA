#pragma once

// Запись носителя хостом.
//
// Отдельный заголовок, чтобы этот путь был виден только эмулятору карты.
// Запись насквозь, грязных секторов не бывает.

#include <cstdint>

#include "devices/storage/storage.h"

namespace devices::storage {

// Записать сектор на носитель хозяина. Номер хозяина обязателен: стороны
// смотрят в разные носители, и писать надо туда же, откуда читали.
// Запись насквозь, кэш обновляется: хост сразу видит своё значение.
bool storage_write(sd::SdOwner owner, uint32_t lba, const uint8_t* src);

// Писатель на носитель один: первый хозяин, начавший запись, пишет на
// него до перезагрузки. У каждого эмулятора своя картина FAT, и запись
// второго на тот же носитель портит её первому, а бит защиты от записи
// софт почти не смотрит. Чтение не запрещено; на разных носителях хозяева
// друг другу не мешают.
//
// true - хозяин пишет (захватил носитель сейчас или раньше). Зовётся и из
// обработчика шины: только атомарное сравнение с обменом.
bool storage_claim_writer(sd::SdOwner owner);

// Снять замок со всех носителей: машину сбросили, драйверы её начинают
// с чистой картины.
void storage_release_writers();

// Кто пишет на носитель, для журнала; None - никто.
sd::SdOwner storage_writer(hal::Medium m);
uint32_t storage_writes_denied();

} // namespace devices::storage
