#pragma once

// Банк инструментов с карты памяти.
//
// Во флеше банку отдано 15 МБ, это предел микросхемы. Собранный банк Timbres
// of Heaven - 113 МБ. На карте место есть, а читать можно тем же путём,
// каким сэмплы попадают в PSRAM: прогон распаковывается кусками.
// Самый большой сжатый прогон у этого банка
// 699 КБ - его нельзя было бы буферизовать.
//
// Таблицы (пресеты, инструменты, огибающие, keymap, сэмплы - 612 КБ у
// Timbres) читаются один раз при старте в отдельный кусок PSRAM: доступ
// к ним вразнобой, с карты это был бы сектор на обращение. PCM остаётся
// на карте.
//
// Ядра: монтирование и чтение таблиц идут на Core1 при старте - после
// подъёма шины и USB, но ДО сеанса, то есть пока машина ещё в сбросе и
// треков нет. Дальше картой владеет тот же цикл Core1, загрузка трека и
// bank_make_resident тоже на нём. Блокировок нет и не нужно: распределитель
// PSRAM за всё это время видит одно ядро.
//
// Файловая система на карте одна, драйверов три: наш FatFs (только
// чтение), esxDOS на Z80 и то, что поднимет пользователь. Если хост
// перезапишет midi.ssb во время работы, наши цепочки кластеров станут
// неверными. Открытый файл банка трогать с хоста нельзя.

#include "core/bank/bank_reader.h"

// Имя в корне карты. Формат 8.3, чтобы файл был виден и без поддержки
// длинных имён.
#ifndef SOUNDSINTH_BANK_SD_PATH
#define SOUNDSINTH_BANK_SD_PATH "/midi.ssb"
#endif

namespace player {

// Взять банк с карты. false - банка нет или он не открылся; звать после
// storage_init() и до сеанса. Причина пишется в лог, кода ошибки нет: при
// любом отказе играет банк из флеша.
//
// pump зовётся между куска́ми чтения таблиц: сотни миллисекунд, за которые
// иначе не двинется ничего асинхронного (перечисление USB).
bool bank_sd_open(soundsinth::bank::Bank& out, void (*pump)() = nullptr);

} // namespace player
