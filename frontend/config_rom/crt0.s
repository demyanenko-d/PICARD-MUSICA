;; crt0.s - старт ПЗУ-конфигуратора.
;;
;; Это ПЗУ, а не программа: плата подставляет его машине на 0x0000
;; механизмом DivMMC, и машина стартует прямо сюда после сброса. ПЗУ
;; машины в этом режиме не видно вовсе.
;;
;; РАСКЛАДКА ПАМЯТИ
;;
;;   0x0000          сброс
;;   0x0038          кадровое прерывание, IM 1
;;   0x0066          NMI: кнопка на плате есть, без retn она уводит в мусор
;;   0x0070          код и данные образа
;;   0x1C00..0x1FFF  знакогенератор, нижняя половина (область _FONT)
;;   0x2000..0x3FFF  страница настроек, её пишет плата
;;   0x4000..0x5AFF  экран
;;   0x6000          данные, растут вверх
;;   0x7FFF          стек, растёт вниз
;;
;; Прерывание - IM 1, а не IM 2: таблица векторов нужна там, где 0x0038
;; занято чужим ПЗУ, а здесь этот байт наш.
;;
;; Всё, что нужно машине, лежит ниже 0x8000: верхние 32 КБ не трогаются
;; вовсе, и конфигуратору безразличен объём её памяти.

        .module crt0
        .globl  _main
        .globl  _fw_kbd_scan
        .globl  _fw_ticks
        .globl  l__INITIALIZER
        .globl  s__INITIALIZED
        .globl  s__INITIALIZER
        .globl  s__DATA
        .globl  l__DATA

STACK   .equ    0x7FFF

;; Векторы и код - одна область от нуля: прибитые области компоновщик
;; раскладывает в своём порядке, и _GSINIT ложится поверх кода. Здесь
;; порядок задан явно, а выравнивание считает ассемблер; сборка сверяет
;; байты по 0x0000, 0x0038 и 0x0066.
        .area   _CODE

        di
        jp      init

        ;; di плюс jp - четыре байта; дальше до вектора прерывания.
        .ds     0x0038 - 4
;; Кадровое прерывание. Опрос клавиатуры тот же, что у приложения TR-DOS:
;; и клавиши машины, и клавиши USB приходят через порт 0xFE, и гашение
;; дребезга с автоповтором у них общее.
        push    af
        push    bc
        push    de
        push    hl
        push    ix
        ld      hl, (_fw_ticks)
        inc     hl
        ld      (_fw_ticks), hl
        call    _fw_kbd_scan
        pop     ix
        pop     hl
        pop     de
        pop     bc
        pop     af
        ei
        reti

        ;; Обработчик занял 25 байт, считая от 0x0038.
        .ds     0x0066 - (0x0038 + 25)
;; NMI: кнопка на плате ведёт эту линию, и без возврата нажатие уводило бы
;; процессор в мусор.
        retn


;; Порядок областей задаёт раскладку.
        .area   _HOME
        .area   _INITIALIZER
        .area   _GSINIT
        .area   _GSFINAL

        .area   _DATA
_fw_ticks::
        .ds     2
        .area   _INITIALIZED
        .area   _BSEG
        .area   _BSS
        .area   _HEAP

        .area   _GSINIT
init:
        di
        ld      sp, #STACK

        ;; Обнулить неинициализированные данные: в ОЗУ машины после
        ;; включения мусор, а библиотека ждёт нулей в счётчиках и кольцах.
        ld      hl, #s__DATA
        ld      de, #s__DATA + 1
        ld      bc, #l__DATA - 1
        ld      a, b
        or      a, c
        jr      z, crt0_no_data
        ld      (hl), #0
        ldir
crt0_no_data:

        ;; Начальные значения глобальных переменных Си: образ один, память
        ;; под них другая.
        ld      bc, #l__INITIALIZER
        ld      a, b
        or      a, c
        jr      z, crt0_no_init
        ld      de, #s__INITIALIZED
        ld      hl, #s__INITIALIZER
        ldir
crt0_no_init:

        ;; Прерывание своё: вектор уже лежит по 0x0038, ставить таблицу не
        ;; надо.
        im      1
        ei

        call    _main

        ;; main() не возвращается: выход из конфигуратора - это
        ;; перезагрузка платы, и машину она уводит в сброс. Сюда попадаем,
        ;; только если что-то пошло не так.
        di
crt0_halt:
        halt
        jr      crt0_halt

        .area   _GSFINAL
        ret
