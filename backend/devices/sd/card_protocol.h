#pragma once

// Карта SD/SDHC на SPI1 - нижний слой носителя.
//
// Подключение (по таблице функций pico-sdk, io_bank0.h):
//   GPIO40 SPI1_RX   -> вывод 7 карты, DAT0 (MISO)
//   GPIO41 SPI1_SS_N -> вывод 2, CD/DAT3 (CS)
//   GPIO42 SPI1_SCLK -> вывод 5, CLK
//   GPIO43 SPI1_TX   -> вывод 3, CMD (MOSI)
//
// Линии Card Detect на плате нет: "карта на месте" - это успешная
// инициализация.
//
// Интерфейс синхронный, посекторный. Сектор на SPI на полной скорости -
// около 200 мкс; асинхронность добавила бы состояний без выигрыша. Единица
// арбитража - сектор.
//
// Не из ISR: обмен блокирующий. При старте зовёт Core0 (storage_init,
// самопроверка сектора 0, bank_sd_open) до запуска Core1, дальше только
// цикл Core1 (sd_spi_task, чтение PCM банка). Два ядра одновременно сюда не
// заходят, поэтому блокировок нет.

#include <cstdint>

namespace devices::sd {

// Тип карты определяется при инициализации: у SDSC адрес в командах
// чтения и записи - байты, у SDHC/SDXC - номер сектора. Перепутав,
// читаешь не то место.
enum class SdKind : uint8_t { None = 0, Sdsc = 1, Sdhc = 2 };

struct SdInfo {
    bool     present      = false;
    SdKind   kind         = SdKind::None;
    uint32_t sector_count = 0;   // из CSD; 0, если разобрать не удалось
};

// Полная инициализация: SPI на 400 кГц, CMD0/CMD8/ACMD41/CMD58, чтение
// CSD, переход на рабочую частоту. Блокирующая: исправная карта - 12 мс
// по логу (SDHC 32 ГБ, строка "sd: ..., init N ms"), потолок около 4 с (два
// прохода ACMD41 по 1.5 с и CMD1 1 с). В прошивке зовётся один раз, при
// старте; после сбоя карту переинициализируют сами чтение и запись.
bool sd_card_init();

const SdInfo& sd_card_info();

// Строка об итоге последнего рукопожатия: опознание носителя или шаг, на
// котором карта замолчала, с числами этого шага. Само рукопожатие не
// печатает: оно идёт и при переинициализации, то есть с Core1 под
// загрузчиком, где буфер строки со snprintf стоит 640 байт стека. Звать с
// Core0 после storage_init и из задачи логгера; sd_card_log_health зовёт
// сам, когда была переинициализация.
void sd_card_log_handshake();

// Чтение и запись одного сектора (512 байт). false - карта не ответила
// или ответила ошибкой, содержимое dst не определено.
bool sd_card_read_sector(uint32_t lba, uint8_t* dst);
bool sd_card_write_sector(uint32_t lba, const uint8_t* src);

// Строка "sd: носитель: ..." в лог: сбои чтения сектора по причинам с начала
// работы, в скобках прирост за период, печатается и с нулями. Хост после
// сбоя видит только таймаут. Звать из задачи логгера по расписанию.
void sd_card_log_health();

// Кого звать, пока драйвер ждёт карту: опрос ACMD41 и CMD1 при
// инициализации (до 4 с), токен данных (200 мс) и конец записи (500 мс).
// Без этого протокол хоста всё это время не обслуживается, а кольцо команд
// держит два кадра. Зовётся не чаще раза в миллисекунду и только снаружи
// транзакции: обслуживать карту отсюда нельзя - вложенное чтение сектора
// начало бы команду посреди чужой при опущенном CS.
//
// Ставит оркестратор, когда берёт карту на Core1; на Core0 при старте
// пусто. Вложенные sd_card_read_sector и sd_card_write_sector из него
// возвращают false.
void sd_card_set_wait_service(void (*fn)(void* user), void* user);

} // namespace devices::sd
