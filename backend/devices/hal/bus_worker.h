#pragma once

// Время шины и поток устройства, которое считает своё состояние вслед за
// шиной (Beta Disk). Определяет порт.
//
// Время - отсчёты по 0.5 мкс от включения. Метка для обработчиков шины -
// младшие 32 разряда того же счёта: дёшево, без чтения 64 разрядов.
//
// Поток и обработчики шины идут на одном ядре: обработчик вытесняет поток,
// поток - основной цикл. Будят поток bus_worker_kick из обработчика шины и будильник
// на момент времени шины. На одном ядре стоит очередь событий устройства:
// её порядок держит барьер компилятора, а не памяти. Порт, который так не
// может, обязан дать другой механизм обмена.

#include <cstdint>

namespace devices::hal {

// Часы шины указателем (bus_clock_now) и тело потока.
using ClockFn  = uint64_t (*)();
using WorkerFn = void (*)();

uint64_t bus_clock_now();
uint32_t bus_clock_stamp();

// fn - тело потока. Звать на ядре, где обработчики шины.
void bus_worker_init(WorkerFn fn);
void bus_worker_kick();
// Разбудить к моменту at; прошедший - сразу.
void bus_worker_alarm(uint64_t at);
// Короткая секция потока без прерываний: публикация ответов не ложится
// поверх снятия бита обработчиком шины. Не дольше сотни тактов.
uint32_t bus_worker_lock();
void bus_worker_unlock(uint32_t saved);

} // namespace devices::hal
