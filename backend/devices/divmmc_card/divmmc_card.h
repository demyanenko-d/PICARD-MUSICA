// Карты DivMMC, которыми плата притворяется для хоста. Работают при любой
// дисковой системе; подстановка памяти DivMMC (порт 0xE3) - отдельно.
//
// Два порта на обе карты:
//   0xE7  запись - выбор: бит 0 - карта 1, бит 1 - карта 2, ноль выбирает
//   0xEB  запись - отдать байт выбранной карте (MOSI)
//         чтение - ответ на предыдущий обмен; сразу после чтения
//                  запускается холостой обмен (0xFF), его ответ получит
//                  следующее чтение
//
// Карта, выключенная настройками, не выбирается: машина видит на её месте
// пустую шину, 0xFF. Выбраны обе - обмен идёт с первой.

#include <cstdint>

namespace devices::divmmc_card {

inline constexpr uint8_t kPortCtrl = 0xe7;
inline constexpr uint8_t kPortData = 0xeb;

// Зарегистрировать порты. Звать после того, как шина готова принимать
// обработчики, и после storage_init(). Хотя бы одна карта включена.
void divmmc_card_init(bool card1, bool card2);

} // namespace devices::divmmc_card
