#pragma once

// Мост между автоматом General Sound (devices::gs::GsDevice) и шиной
// Z80.
//
// Протокол GS платформонезависим и покрыт ПК-тестами; здесь только
// привязка к портам, кольцо приёма и передача накопленного трекеру.
// Логики команд здесь нет.
//
// Порты GS:
//
//   0xbb  запись  GSCOM   команда
//   0xbb  чтение  GSSTAT  биты состояния
//   0xb3  запись  GSDAT   данные ZX -> GS
//   0xb3  чтение  GSDAT   данные GS -> ZX
//
// Протокол платы использует 0x63/0x67 (SOUNDSINTH_BUS_PORT_CMD/DAT),
// порты GS свободны.

#include <cstdint>

namespace player::gs {

// Подключить эмуляцию к шине. Звать после подъёма шины порта.
void bridge_init();

// Сброс машины: карта - как по линии RESET, эффекты смолкают, модуль
// выброшен. Звать из основного потока.
void bridge_machine_reset();
// Сброс машины при STOP_MUSIC_ON_RESET=0: обмен с картой обрывается, модуль
// и эффекты играют дальше.
void bridge_machine_reset_light();
// Остановка музыки без сброса (F10): голоса эффектов смолкают.
void bridge_stop_effects();

// Работа основного потока: разобрать записи в порты (команды и их
// аргументы), накопленный модуль отдать загрузчику. Звать с прочей
// периодикой: команда ждёт опроса с взведённым разрядом D0.
void bridge_poll();

// Плеер GS попросил память под модуль (#30): память трека теперь его, до
// release_buffer.
bool bridge_wants_track_memory();

// Вернуть приёмный буфер хранилищу трека: трек запускают через протокол
// платы, плеер GS больше не говорит. Звать, когда движок снят
// (track_load_begin): хранилище пересобирает список свободных страниц.
// Следующая команда загрузки модуля отрежет буфер заново.
void bridge_release_buffer();

// Память трека отдана живому режиму: модуль, разобранный в неё, затёрт.
// #31 после этого не поднимает поколение песни (движок собрался бы над
// живой песней без позиций), #32 не ставит паузу живому сеансу. Звать из
// основного потока Core1.
void bridge_track_memory_taken();

// Какие каналы модуля заняты эффектами. Ноль, если настройка велит играть
// эффекты своими голосами: тогда музыку глушить незачем.
uint32_t bridge_fx_mute_mask();
// Громкость модуля карты (#2A/#35) усилением трека, Q12: 4096 - не модуль
// GS или полная громкость.
uint16_t bridge_track_gain();

// Печать состояния эмуляции, если с ней говорили: счётчики (unknown -
// какой команды не хватило), четыре частые команды (порты GS в диапазоне
// ATA у divIDE: стучаться может и ПЗУ esxDOS), до шести раз первые
// обращения к портам. Звать из задачи логгера.
void bridge_log_stats();

} // namespace player::gs
