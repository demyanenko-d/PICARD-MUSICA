#pragma once

// USB-хост на встроенном контроллере RP2350.
//
// Живёт на Core1 и только на нём: прерывание регистрируется на вызывающем
// ядре, а стек собран без операционной системы (OPT_OS_NONE) и блокировок
// внутри не имеет. Обращаться к нему с Core0 нельзя.
//
// Каналов DMA не занимает ни одного - контроллер возит байты сам.
//
// Разъём должен быть хостовым: плата обязана подавать 5 В на VBUS, иначе
// устройство не поднимется, и в журнале не будет ни одной строки о
// подключении.

#include <cstdint>

namespace rp2350::usb {

// Поднять стек. Звать с Core1 после того, как поднята шина: прерывание
// хоста ставится ниже всех шинных, чтобы не задерживать ответ машине.
void host_init();

// Виток стека. Звать из цикла Core1; сам по себе не блокирует.
void host_task();

// Отдать время обслуживанию шины один раз. Зовут ожидания внутри стека:
// обмен с флешкой и паузы перечисления. Без этого шина на время паузы
// замирает - прерывания идут, но кооперативная часть цикла стоит.
void yield_to_bus();
void set_wait_service(void (*fn)(void*), void* user);

// Сколько устройств сейчас подключено - для строки журнала.
struct HostStats {
    uint8_t hid_keyboards;
    uint8_t hid_mice;
    uint8_t hid_gamepads;
    uint8_t msc_drives;
    uint32_t reports; // принятых отчётов HID, монотонно
    // Заказы, восстановленные сторожевым витком. В норме ноль: ненулевой
    // значит, что интерфейс замолчал и его вернули.
    uint32_t rearms;
    // Самый долгий виток host_task(). Виток крутит ядро шины, поэтому
    // число говорит, насколько стек способен задержать кооперативную
    // часть цикла; прерывания он не гасит.
    uint32_t task_max_us;
};
HostStats host_stats();

// Строка о состоянии хоста в журнал. Звать из задачи логгера.
void host_log_health();

} // namespace rp2350::usb
