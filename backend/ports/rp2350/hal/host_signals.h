#pragma once

// Отпускание импульсных линий сброса и NMI. Звать из витка того же ядра,
// что подаёт сигналы: линии держатся по сроку, а не занятым ожиданием.

namespace rp2350::hal {

void host_signals_tick();

// Разрешить плате подавать сброс по своей воле: F12 и тройка.
//
// Линию плата ведёт всегда, в том числе при запрете: она остаётся выходом
// в неактивном уровне. Отпустить её в высокоимпедансное нельзя - за ней
// инвертор, и плавающий вход у него это неопределённость.
//
// Удержания на время загрузки запрет не касается. Машина стоит в сбросе,
// пока не готовы PIO и DMA шины: отпустить её раньше значит пустить на
// ненастроенную шину. Отпускает цикл сеанса, когда шина поднята.
void host_signals_allow_reset(bool allow);

} // namespace rp2350::hal
