#pragma once

// Флешка на USB: подключение, ёмкость и чтение сектора.
//
// Стек MSC асинхронный, а носитель у платы читается вызовом, который
// возвращается с данными. Поэтому чтение здесь ждёт в цикле, крутя виток
// стека, - как эмулятор карты ждёт SPI. Кому отдавать время в это время,
// решает yield_to_bus() хоста: без неё ожидание крутит только USB, и шина
// на это время замирает.
//
// Всё зовётся с Core1: стек собран без операционной системы.

#include <cstdint>

namespace rp2350::usb {

inline constexpr uint32_t kMscSectorBytes = 512;

void msc_task();

bool msc_present();
uint32_t msc_sector_count();
// Дисков подключено и из них ВЗЯТО в работу. Числа расходятся, когда у
// диска чужой размер сектора: подключён есть, работающего нет, и строка
// "дисков 1" без второго числа говорит о диске, которого нет.
uint8_t msc_drive_count();
uint8_t msc_drive_taken();

// Один сектор. false - диска нет, обмен не начался или устройство
// ответило отказом.
bool msc_read(uint32_t lba, uint8_t* dst);

// Пачка подряд идущих секторов одной командой READ(10). Замер платы:
// T(n) = 469 + 426*n мкс, то есть накладные расходы команды - больше
// половины цены одиночного чтения.
bool msc_read_run(uint32_t lba, uint32_t count, uint8_t* dst);
bool msc_write(uint32_t lba, const uint8_t* src);

// Время обмена с флешкой. У карты такие счётчики есть давно, а у
// флешки не было ни одного: сколько стоит круг CBW-данные-CSW, было
// неизвестно. От этого числа зависит, имеет ли смысл просить пачку
// секторов одной командой вместо одного.
struct MscStats {
    uint32_t reads; // успешных чтений сектора
    uint32_t writes;
    uint32_t failed; // обменов без данных: сумма четырёх ниже
    // Причины врозь: лечатся они по-разному, а при DISKSYS_MEDIA=usb машина
    // получает мусор, и в журнале не должно оставаться одного числа.
    uint32_t not_started; // стек не принял команду
    uint32_t csw_bad;     // устройство ответило ненулевым статусом
    uint32_t timeouts;    // не ответило вовсе: флешку выдернули
    uint32_t reentry;     // обмен уже шёл: позвали не из цикла Core1
    uint32_t read_max_us;
    uint64_t read_total_us; // микросекунды: в миллисекундах короткие обмены теряются
    uint32_t write_max_us;
    uint64_t write_total_us;
};

MscStats msc_stats();

} // namespace rp2350::usb
