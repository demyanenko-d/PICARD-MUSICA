// Банк инструментов с карты: больше 15 МБ флеша (Timbres of Heaven - 113 МБ).
// Таблицы читаются при старте в PSRAM, PCM прогонами с карты.
// Только Core1 и до сеанса, поэтому без блокировок. Открытый midi.ssb с хоста
// не трогать: цепочки кластеров FatFs станут неверными.

#include "core/bank/bank_reader.h"

// Путь в корне карты без префикса тома: том по умолчанию - карта
// (kVolumeCard). Формат 8.3, чтобы файл был виден и без поддержки длинных
// имён.
#ifndef SOUNDSINTH_BANK_SD_PATH
#define SOUNDSINTH_BANK_SD_PATH "/midi.ssb"
#endif

namespace player {

// Взять банк с карты. false - банка нет или он не открылся; звать после
// storage_init() и до сеанса. Причина пишется в лог, кода ошибки нет: при
// любом отказе играет банк из флеша.
//
// Между кусками чтения таблиц (сотни миллисекунд на полный банк) крутит
// виток USB-хоста: без него перечисление не двигается, и клавиатура ждёт
// банк.
bool bank_sd_open(soundsinth::bank::Bank& out);

} // namespace player
